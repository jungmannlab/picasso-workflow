@dataclass
class MappedStep:
    """One reconstructed module derived from a manual processing step.

    Parameters
    ----------
    source : str
        The raw ``Generated by`` / ``Wrapped by`` string of the manual step.
    module_name : str
        Target picasso-workflow module (or ``"manual"`` for a placeholder).
    params : dict
        Best-guess parameters for the module.
    confidence : str
        One of :data:`CONF_OK`, :data:`CONF_RETRO`, :data:`CONF_LOW`,
        :data:`CONF_UNMAPPED`.
    cross_channel : bool
        Whether this module needs cross-channel data (marks the boundary).
    messages : list[str]
        Human-readable notes for the review table.
    """

    source: str
    module_name: str
    params: dict = field(default_factory=dict)
    confidence: str = CONF_OK
    cross_channel: bool = False
    messages: list[str] = field(default_factory=list)
    source_file: str | None = None  # manual .hdf5 that first saved this step
    info_dict: dict | None = None  # the raw info step dict it was mapped from


@dataclass
class ChannelChain:
    """The discovered manual-analysis artefacts for one channel."""

    tag: str  # "ALFA-L1" (channel part of the manual base name)
    dataset: str  # "Cell 1" (dataset part of the manual base name)
    base_hdf5: str | None  # shortest-stem localization file
    deepest_hdf5: str  # longest-chain file (authoritative info source)
    raw_filepath: str | None  # resolved raw movie (.ome.tif)
    picks_path: str | None  # *_picks*.yaml if present
    info_steps: list[dict] = field(default_factory=list)
    # number of info steps baked into base_hdf5 (the downstream-mode start)
    base_info_len: int = 0
    # sorted (info_doc_count, hdf5_basename) for every file in the chain, used
    # to attribute each step to the manual file that first saved it
    file_lengths: list = field(default_factory=list)
    steps: list[MappedStep] = field(default_factory=list)


@dataclass
class ReconstructionResult:
    """Everything the wizard needs to populate the GUI.

    Attributes
    ----------
    tree_data : dict
        The aggregation Files-tree structure (``datasets`` / ``channels`` /
        ``file_paths`` / ``conditions`` / ``tile_params``).
    single_modules, agg_modules : list[tuple[str, dict]]
        Single-dataset and aggregation module lists in ``WorkflowRunner``
        ``(name, parameters)`` form.
    review : list[dict]
        One row per reconstructed module (channel-agnostic view) with keys
        ``module``, ``source``, ``confidence``, ``messages``, ``stage``.
    channels : list[str]
        Channel tags in order.
    errors : list[str]
        Consistency / validation findings (empty when clean).
    raw_root : str or None
        The dataset root where raw movies were located (``None`` if not found).
    """

    tree_data: dict
    single_modules: list
    agg_modules: list
    review: list
    channels: list
    errors: list = field(default_factory=list)
    raw_root: str | None = None
    # Per-module metadata (source / confidence / notes), parallel to
    # single_modules / agg_modules, for the editable review table.
    single_meta: list = field(default_factory=list)
    agg_meta: list = field(default_factory=list)


# ---------------------------------------------------------------------------
# YAML / picasso I/O helpers (isolated so tests can monkeypatch them).
# ---------------------------------------------------------------------------
def _load_info(info_path):
    """Return the ordered list of info-step dicts from a ``.yaml`` sidecar.

    picasso stores the info as several ``---``-separated YAML documents; the
    first describes the movie/localizations, each later one a processing step.
    """
    with open(info_path, "r") as f:
        docs = [d for d in yaml.safe_load_all(f) if d is not None]
    return docs


def _count_info_docs(yaml_path):
    """Count the YAML documents (info steps) in a sidecar, cheaply.

    Counts bare ``---`` separators without parsing the (large) movie-metadata
    document; the count is ``separators + 1``.
    """
    seps = 0
    with open(yaml_path, "r") as f:
        for line in f:
            if line.strip() == "---":
                seps += 1
    return seps + 1


def _file_for_index(file_lengths, info_index):
    """Return the manual file that first saved info step ``info_index``.

    ``file_lengths`` is a sorted ``[(doc_count, basename), ...]``; the step at
    ``info_index`` first appears in the shortest file whose info includes it
    (``doc_count > info_index``).
    """
    for doc_count, name in file_lengths:
        if doc_count > info_index:
            return name
    return None


def _load_picks_yaml(picks_path):
    """Return ``(centers, diameter_nm, shape)`` from a picasso picks yaml."""
    with open(picks_path, "r") as f:
        data = yaml.safe_load(f)
    centers = [tuple(c) for c in data.get("Centers", [])]
    diameter = data.get("Diameter (nm)")
    shape = data.get("Shape", "Circle")
    return centers, diameter, shape


def _load_locs(hdf5_path):
    """Load a localization table via the picasso boundary.

    Confined here because it is the one hard picasso dependency of the engine
    (needed only for the ``find_similar`` retro-calculation). Returns
    ``(locs, info)``.
    """
    from picasso_workflow import _picasso_api

    return _picasso_api.io.load_locs(hdf5_path)


def _report(progress, message, fraction):
    """Invoke an optional progress callback ``progress(message, fraction)``.

    ``fraction`` is a float in ``[0, 1]`` for determinate progress or ``None``
    for an indeterminate (busy) phase. A ``None`` ``progress`` is a no-op, so
    the engine stays usable headless/in tests.
    """
    if progress is not None:
        progress(message, fraction)


class ReconstructionCancelled(Exception):
    """Raised to abort an in-progress reconstruction cooperatively."""


def _source_versions(info_steps):
    """Distinct picasso versions recorded across a channel's info steps.

    From the ``"Picasso version"`` key (picasso >=1.0) or the version embedded
    in ``"Generated by: Picasso v<ver> ..."``. Returns a sorted list.
    """
    versions = set()
    for step in info_steps or []:
        if not isinstance(step, dict):
            continue
        ver = step.get("Picasso version")
        if ver:
            versions.add(str(ver))
            continue
        match = re.search(
            r"Picasso:? v([0-9][0-9A-Za-z.\-]*)",
            str(step.get("Generated by", "")),
        )
        if match:
            versions.add(match.group(1))
    return sorted(versions)


def _check_cancel(should_cancel):
    """Raise :class:`ReconstructionCancelled` if ``should_cancel()`` is true.

    ``should_cancel`` is an optional ``() -> bool`` polled at checkpoints (per
    channel) so a long scan can be stopped between channels; a single picasso
    locs load is not itself interruptible.
    """
    if should_cancel is not None and should_cancel():
        raise ReconstructionCancelled()


