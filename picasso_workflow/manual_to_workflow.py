def _steps_to_modules(steps):
    """Render mapped steps as ``(name, params)`` tuples."""
    return [(s.module_name, dict(s.params)) for s in steps]


# ---------------------------------------------------------------------------
# 7. Consistency / correctness check.
# ---------------------------------------------------------------------------
def validate(single_modules, agg_modules, chains):
    """Run registry validation + wizard-level consistency checks.

    Returns a list of human-readable findings (empty when clean).
    """
    errors = []
    errors += [
        f"single[{msg}"
        for msg in modulespec.validate_workflow(
            single_modules, modulespec.Scope.SINGLE
        )
    ]
    if agg_modules:
        errors += [
            f"aggregation[{msg}"
            for msg in modulespec.validate_workflow(
                agg_modules, modulespec.Scope.AGGREGATION
            )
        ]
    # Every channel should share the same step spine.
    spines = {tuple(s.module_name for s in c.steps) for c in chains if c.steps}
    if len(spines) > 1:
        errors.append(
            "channels have differing step sequences; review per-channel "
            "reconstruction"
        )
    # Required inputs must exist.
    for c in chains:
        if c.raw_filepath and not os.path.exists(c.raw_filepath):
            errors.append(f"raw movie not found for channel {c.tag}")
    # No unresolved placeholders.
    for c in chains:
        for s in c.steps:
            if s.confidence == CONF_UNMAPPED:
                errors.append(f"channel {c.tag}: unresolved step '{s.source}'")
    return errors


# ---------------------------------------------------------------------------
# 8. Top-level entry point.
# ---------------------------------------------------------------------------
def reconstruct_workflow(
    manual_dir,
    raw_root=None,
    pixelsize=130.0,
    start_from="raw",
    progress=None,
    should_cancel=None,
):
    """Reconstruct an aggregation workflow from a manual-analysis folder.

    Parameters
    ----------
    manual_dir : str
        Folder holding the manual ``.hdf5`` step chain (e.g. the
        ``analysis_manual`` folder) -- the user browses straight to it.
    raw_root : str, optional
        Dataset root holding the raw acquisition subfolders, used to point the
        reconstructed ``load_dataset_movie`` steps at the raw movies. If
        omitted, it is auto-detected by walking up from ``manual_dir`` (the raw
        folders may sit several levels above). When no raw movie can be located,
        the loader falls back to the manual localization file. Unused when
        ``start_from="localizations"``.
    pixelsize : float
        Camera pixel size in nm, used for the ``find_similar`` retro-calc.
    start_from : {"raw", "localizations"}
        ``"raw"`` re-localizes from the raw movies (the full pipeline).
        ``"localizations"`` starts downstream from each channel's manual
        localized file: load it directly and run only the steps applied after
        it, skipping the baked-in localize/undrift steps (and raw lookup).
    progress : callable, optional
        ``progress(message, fraction)`` callback for UI feedback;
        ``fraction`` is in ``[0, 1]`` or ``None`` for an indeterminate phase.
    should_cancel : callable, optional
        ``() -> bool`` polled per channel; a true value aborts with
        :class:`ReconstructionCancelled`.

    Returns
    -------
    ReconstructionResult
    """
    _report(progress, "Scanning analysis folder…", None)
    chains = scan_folder(
        manual_dir, progress=progress, should_cancel=should_cancel
    )
    if not chains:
        raise ValueError(f"no manual-analysis channels found in {manual_dir}")

    # In raw mode, locate the raw movies by the MicroManager naming convention
    # (direct stat, no recursive tree walk); auto-detect the root if not given.
    effective_raw_root = None
    if start_from == "raw":
        _report(progress, "Locating raw data…", None)
        effective_raw_root = raw_root or detect_raw_root(manual_dir)
        if effective_raw_root:
            for chain in chains:
                chain.raw_filepath = _raw_in_root(
                    effective_raw_root, _channel_basename(chain)
                )

    # Reserve the first 90% of the bar for the per-channel pass (the slow part:
    # each channel with picks loads its full localization file for the
    # pick retro-calc); the last 10% is the quick fold/validate.
    total = len(chains)
    for i, chain in enumerate(chains):
        _check_cancel(should_cancel)
        frac = 0.9 * i / total
        _report(
            progress,
            f"Reconstructing channel {i + 1}/{total}: {chain.tag}…",
            frac,
        )
        map_chain(chain, pixelsize=pixelsize, start_from=start_from)
        needs_locs = (
            chain.picks_path
            or chain.pick_exports
            or any(s.module_name == "picasso_picked_locs" for s in chain.steps)
        )
        if needs_locs:
            _report(
                progress,
                f"Channel {i + 1}/{total} ({chain.tag}): loading "
                "localizations for pick retro-calculation…",
                frac,
            )
        apply_find_similar_retrocalc(chain, pixelsize=pixelsize)
        apply_pick_similar_retrocalc(chain, manual_dir, pixelsize=pixelsize)
        # Re-derive undrift-from-picked's picks in-workflow (find_similar with
        # the recovered thresholds) instead of loading the manual pick files.
        apply_pick_similar_for_undrift(chain, pixelsize=pixelsize)

    _report(progress, "Folding and validating the workflow…", 0.95)

    # Split each channel, then fold the single stage with $$map.
    per_channel_single = []
    per_channel_agg = []
    for chain in chains:
        single_steps, agg_steps = split_stages(chain.steps)
        per_channel_single.append(single_steps)
        per_channel_agg.append(agg_steps)

    tags = [c.tag for c in chains]
    single_folded, tile_params, diverge_warnings = diff_single_stage(
        per_channel_single, tags
    )
    # The aggregation spine is taken from the first channel (same across all);
    # unlike the single stage it is not tiled per channel, so warn if the
    # per-channel aggregation parameters actually differ.
    agg_steps = per_channel_agg[0] if per_channel_agg else []
    diverge_warnings += _agg_param_divergence(per_channel_agg, tags)

    single_spine = per_channel_single[0] if per_channel_single else []
    single_modules = list(single_folded)
    single_meta = [_step_meta(s) for s in single_spine]
    single_modules.append(_save_single_bridge())
    single_meta.append(_bridge_meta())
    save_index = len(single_modules) - 1

    agg_modules = []
    agg_meta = []
    if agg_steps:
        agg_modules.append(("analysis_documentation", {}))
        agg_modules.append(_load_aggregate_bridge(save_index))
        agg_meta += [_bridge_meta(), _bridge_meta()]
        # The first agg step is the cross-channel boundary module itself.
        agg_modules += _steps_to_modules(agg_steps)
        agg_meta += [_step_meta(s) for s in agg_steps]
        agg_modules.append(("save_datasets_aggregated", {}))
        agg_meta.append(_bridge_meta())

    tree_data = _build_tree_data(chains, tile_params)
    review = _build_review(chains)
    errors = validate(single_modules, agg_modules, chains) + diverge_warnings

    if start_from == "raw" and not effective_raw_root:
        errors.append(
            "raw data folder not found; workflows will load the manual "
            "localization files instead of re-localizing from the movies"
        )

    versions = _source_versions(chains[0].info_steps) if chains else []
    if versions:
        errors.append(
            "info: steps recorded with picasso "
            + ", ".join(versions)
            + "; the workflow will run on the installed picasso (>=1.0). "
            "Physical parameters (nm, counts) are version-independent; the "
            "fit-method name is normalized for re-localization."
        )

    _report(progress, "Done.", 1.0)
    return ReconstructionResult(
        tree_data=tree_data,
        single_modules=single_modules,
        agg_modules=agg_modules,
        review=review,
        channels=[c.tag for c in chains],
        errors=errors,
        raw_root=effective_raw_root,
        single_meta=single_meta,
        agg_meta=agg_meta,
    )


def _step_meta(step):
    """Per-module review metadata for one mapped step."""
    return {
        "source": step.source,
        "confidence": step.confidence,
        "notes": "; ".join(step.messages),
        "source_file": step.source_file,
    }


def _bridge_meta():
    """Review metadata for a wizard-added bridge/plumbing module."""
    return {
        "source": "(added by wizard)",
        "confidence": CONF_OK,
        "notes": "",
        "source_file": None,
    }


def _build_tree_data(chains, tile_params):
    """Assemble the GUI aggregation Files-tree structure."""
    datasets = []
    for c in chains:
        if c.dataset not in datasets:
            datasets.append(c.dataset)
    channels = [c.tag for c in chains]
    file_paths: dict[str, dict] = {}
    for c in chains:
        file_paths.setdefault(c.dataset, {})[c.tag] = (
            c.raw_filepath or c.base_hdf5 or c.deepest_hdf5
        )
    tile = {
        col: {"scope": "channel", "default": None, "values": vals}
        for col, vals in tile_params.items()
    }
    return {
        "datasets": datasets,
        "channels": channels,
        "file_paths": file_paths,
        "conditions": {},
        "tile_params": tile,
    }


def _agg_param_divergence(per_channel_agg, channels):
    """Warn when per-channel aggregation-stage parameters differ.

    The aggregation stage runs once (it is not tiled per channel), so only the
    first channel's parameters are used. Unlike the single stage, differing
    per-channel values cannot be expressed via ``$$map`` there, so surface them
    for the user rather than letting channel-0 values silently win.
    """
    warnings = []
    if len(per_channel_agg) < 2:
        return warnings
    spine = per_channel_agg[0]
    for pos, step in enumerate(spine):
        for ci in range(1, len(per_channel_agg)):
            other = per_channel_agg[ci]
            if pos >= len(other) or other[pos].module_name != step.module_name:
                continue
            if other[pos].params != step.params:
                warnings.append(
                    f"channel {channels[ci]} has different {step.module_name} "
                    f"parameters in the aggregation stage; using channel "
                    f"{channels[0]} values (aggregation is not per-channel)"
                )
    return warnings


def _build_review(chains):
    """Build the per-module review rows from the first channel's spine."""
    review = []
    if not chains:
        return review
    single_steps, agg_steps = split_stages(chains[0].steps)
    for s in single_steps:
        review.append(_review_row(s, "single"))
    for s in agg_steps:
        review.append(_review_row(s, "aggregation"))
    return review


def _review_row(step, stage):
    return {
        "module": step.module_name,
        "source": step.source,
        "confidence": step.confidence,
        "messages": list(step.messages),
        "stage": stage,
        "params": dict(step.params),
    }
