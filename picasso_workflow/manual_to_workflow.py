def _source_string(step):
    """Return the identifying string of an info step dict."""
    return str(step.get("Generated by") or step.get("Wrapped by") or "")


# Processing steps map to the *picasso-set* (``picasso_*``) modules, which
# recapitulate native picasso 1:1, for maximal fidelity to what was done by
# hand in the picasso GUI. Only workflow plumbing with no picasso equivalent
# (loaders, ``save_single_dataset``, the cross-channel aggregation modules) and
# the picasso-workflow-native picks helpers (``find_gold`` / ``find_similar``,
# whose selection parameters picasso never persists) stay native.
#
# Extractors translate the exact picasso info keys (see the picassosr source,
# verified against 0.12.0a3) into each ``picasso_*`` module's parameter names,
# converting nm back to camera pixels where the module expects pixels.
def _px(value_nm, pixelsize):
    """Convert an nm value to camera pixels."""
    return float(value_nm) / float(pixelsize)


def _radius_value(step):
    """Return ``(value, unit)`` for a clusterer ``Radius (<unit>)`` key.

    picasso writes the DBSCAN radius under a unit-tagged key, e.g.
    ``"Radius (nm)"`` or ``"Radius (px)"``. Returns ``None`` if absent.
    """
    for key, val in step.items():
        if isinstance(key, str) and key.startswith("Radius ("):
            unit = key[len("Radius (") :].rstrip(")").strip()
            return val, unit
    return None


# picasso_localize takes a short fit-method alias; older picasso recorded full
# names. Numeric params are version-independent, but this enum changed, so a
# recorded method is normalized to a current alias (or dropped, letting the
# module default) so a re-localize runs on the installed picasso.
_FIT_METHOD_ALIASES = frozenset(
    {
        "mle",
        "mle-gpu",
        "mle-spherical",
        "mle-rotated",
        "lq",
        "lq-spherical",
        "lq-rotated",
        "lq-3d",
        "lq-gpu",
        "mle-3d",
        "spline",
        "spline-mle",
        "spline-gpu",
        "spline-mle-gpu",
        "avg",
    }
)
_LEGACY_FIT_METHODS = {
    "gausslq": "lq",
    "gaussmle": "mle",
    "gausslq-spherical": "lq-spherical",
    "gaussmle-spherical": "mle-spherical",
    "gausslq-rotated": "lq-rotated",
    "gausslq-gpu": "lq-gpu",
    "gaussmle-gpu": "mle-gpu",
    "lsq": "lq",
    "avggauss": "avg",
}


def _normalize_fit_method(value):
    """Map a recorded fit-method name to a current ``picasso_localize`` alias.

    Returns the alias, or ``None`` if it cannot be mapped (then the module's
    default is used rather than a name the installed picasso would reject).
    """
    if not isinstance(value, str):
        return None
    low = value.strip().lower()
    if low in _FIT_METHOD_ALIASES:
        return low
    return _LEGACY_FIT_METHODS.get(low)


def _extract_localize(step, pixelsize):
    """picasso_localize (identify+fit) with the native CLI parameter names.

    The identification entry carries ``Box Size`` / ``Min. Net Gradient``; the
    fit entry carries ``Fit method`` and (picasso >=1.0) ``Fit box size``. The
    fit-method enum changed across picasso versions, so the recorded name is
    normalized to a current alias.
    """
    params = {}
    if "Box Size" in step:
        params["box_side_length"] = step["Box Size"]
    elif "Fit box size" in step:  # picasso >=1.0 fit entry
        params["box_side_length"] = step["Fit box size"]
    if "Min. Net Gradient" in step:
        params["gradient"] = step["Min. Net Gradient"]
    if "Fit method" in step:
        alias = _normalize_fit_method(step["Fit method"])
        if alias is not None:
            params["fit_method"] = alias
    if "Pixelsize" in step:
        params["pixelsize"] = step["Pixelsize"]
    return params


def _extract_undrift_rcc(step, pixelsize):
    params = {}
    if "Segmentation" in step:
        params["segmentation"] = step["Segmentation"]
    return params


def _extract_undrift_aim(step, pixelsize):
    # picasso_undrift_aim takes intersectdist / roiradius in camera pixels;
    # the info records them in nm.
    params = {}
    if "Segmentation" in step:
        params["segmentation"] = step["Segmentation"]
    if "Intersect distance (nm)" in step:
        params["intersectdist"] = _px(
            step["Intersect distance (nm)"], pixelsize
        )
    if "Search regions radius (nm)" in step:
        params["roiradius"] = _px(
            step["Search regions radius (nm)"], pixelsize
        )
    return params


def _extract_link(step, pixelsize):
    # native link_locs: d_max in camera pixels, tolerance in frames. picasso
    # >=1.0 records "Max. distance (nm)" (nm) / "Max. transient dark frames";
    # older files used "Maximum Distance" (px) / "Maximum Transient Dark Time".
    params = {}
    if "Max. distance (nm)" in step:
        params["d_max"] = _px(step["Max. distance (nm)"], pixelsize)
    elif "Maximum Distance" in step:
        params["d_max"] = step["Maximum Distance"]
    if "Max. transient dark frames" in step:
        params["tolerance"] = step["Max. transient dark frames"]
    elif "Maximum Transient Dark Time" in step:
        params["tolerance"] = step["Maximum Transient Dark Time"]
    return params


def _extract_density(step, pixelsize):
    # native density: radius in camera pixels. picasso >=1.0 records it under
    # "Radius (nm)" (nm); older files used "Radius" (already px).
    params = {}
    if "Radius (nm)" in step:
        params["radius"] = _px(step["Radius (nm)"], pixelsize)
    elif "Radius" in step:
        params["radius"] = step["Radius"]
    return params


def _extract_picasso_dbscan(step, pixelsize):
    # picasso_dbscan config: radius in camera px (the module multiplies by
    # pixelsize before calling picasso, which records "Radius (nm)"), and
    # density = picasso's minimum local density (min_samples).
    params = {}
    rad = _radius_value(step)
    if rad is not None:
        value, unit = rad
        params["radius"] = (
            float(value) if unit == "px" else float(value) / pixelsize
        )
    if "Minimum local density" in step:
        params["density"] = step["Minimum local density"]
    return params


def _extract_hdbscan(step, pixelsize):
    # native hdbscan: min_cluster, min_samples.
    params = {}
    if "Min. cluster" in step:
        params["min_cluster"] = step["Min. cluster"]
    if "Min. samples" in step:
        params["min_samples"] = step["Min. samples"]
    return params


def _extract_smlm(step, pixelsize):
    # native smlm_clusterer: radius in nm, min_locs.
    params = {}
    for key in ("Clustering radius xy (nm)", "Clustering radius (nm)"):
        if key in step:
            params["radius"] = step[key]
            break
    if "Min. cluster size" in step:
        params["min_locs"] = step["Min. cluster size"]
    return params


def _extract_g5m(step, pixelsize):
    params = {}
    if "Min. no. locs per molecule" in step:
        params["min_locs"] = step["Min. no. locs per molecule"]
    return params


def _extract_none(step, pixelsize):
    return {}


# Ordered matchers: (lowercased substring of the source string, module,
# extractor). First match wins. Strings are ``f"Picasso v{version} <op>"``, so
# matching is by distinctive token; order resolves substring overlaps
# ("hdbscan" before "dbscan"; "undrift from picked"/"by fiducials" before the
# generic "undrift"; the cross-channel markers before the generic "align").
STEP_MAP = [
    # --- non-pipeline steps with no workflow equivalent -> skipped ---
    # "Convert units" is a px<->nm metadata annotation; "Render : NeNA" is a
    # localization-precision measurement. Neither transforms the data.
    ("convert units", SKIP_MODULE, _extract_none),
    ("nena", SKIP_MODULE, _extract_none),
    # --- picasso-workflow-native cross-channel markers (stay native) ---
    ("register_channels", "register_channels", _extract_none),
    ("channel registration", "register_channels", _extract_none),
    ("combine_channels", "combine_channels", _extract_none),
    # picasso's "Combine" merges the per-channel files (RESI) -> combine_channels
    ("combine", "combine_channels", _extract_none),
    ("align_channels", "align_channels", _extract_none),
    # --- picasso-workflow-native picks helpers (no picasso equivalent) ---
    ("find_gold", "find_gold", _extract_none),
    ("find_similar", "find_similar", _extract_none),
    ("find_structures", "find_structures", _extract_none),
    ("pick_origami", "pick_origami", _extract_none),
    ("undrift_from_picked", "undrift_from_picked", _extract_none),
    ("undrift from picked", "undrift_from_picked", _extract_none),
    # --- picasso-set (1:1 native picasso) processing steps ---
    # The 3D *localization* fit steps ("Fit 3D spline"/"Fit 3D phasor") contain
    # "fit 3d" but are part of localize, so they must precede the generic
    # "fit 3d" row (which is the astigmatism z-fit -> picasso_zfit).
    ("identify", "picasso_localize", _extract_localize),
    ("fit 3d spline", "picasso_localize", _extract_localize),
    ("fit 3d phasor", "picasso_localize", _extract_localize),
    ("fit multi-emitter", "picasso_localize", _extract_localize),
    ("fit 2d", "picasso_localize", _extract_localize),
    ("localize", "picasso_localize", _extract_localize),
    ("fit 3d", "picasso_zfit", _extract_none),
    ("zfit", "picasso_zfit", _extract_none),
    ("undrift by fiducials", "picasso_undrift_fiducials", _extract_none),
    ("aim", "picasso_undrift_aim", _extract_undrift_aim),
    ("undrift", "picasso_undrift_rcc", _extract_undrift_rcc),
    ("render : pick", "picasso_picked_locs", _extract_none),
    # --- clustering: prefer the picasso-set (picasso_*) wrappers, which call
    #     picasso's native clusterer 1:1, for fidelity to the manual GUI run
    #     (consistent with the picasso_* mapping used above). picasso_hdbscan
    #     (min_cluster/min_samples) and picasso_g5m (min_locs) take the same
    #     parameter names the native extractors already recover, so those
    #     extractors are reused; picasso_dbscan needs radius in px + density.
    ("hdbscan", "picasso_hdbscan", _extract_hdbscan),
    ("dbscan", "picasso_dbscan", _extract_picasso_dbscan),
    ("smlm clusterer", "smlm_clusterer", _extract_smlm),
    ("g5m", "picasso_g5m", _extract_g5m),
    ("link", "link_locs", _extract_link),
    ("density", "density", _extract_density),
    ("filter", "filter_locs", _extract_none),
    ("align", "picasso_align", _extract_none),
    # Plain "Render" (not "Render : Pick", matched above; "Render : NeNA"
    # matched by "nena" at the top) renders a display image and does not
    # transform the localizations -> skip it.
    ("render", SKIP_MODULE, _extract_none),
]

# Extra review notes attached to a mapped module (independent of parameters).
NOTES_BY_MODULE = {
    "picasso_picked_locs": (
        "picks saved from the manual Render window; if they came from "
        "pick-similar, switch the module to find_similar and set its "
        "parameters"
    ),
    "combine_channels": (
        "set 'channels' (the tags to combine) and 'tag' (the new name) for "
        "each RESI target, e.g. the GFP rounds -> 'GFP'; add more "
        "combine_channels modules for further targets (non-RESI channels are "
        "left untouched)"
    ),
}


def _registry_fallback(source):
    """Best-effort map an unknown step via the module registry.

    Scans :data:`MODULE_REGISTRY` for a module whose name or picasso-symbol
    last component appears as a word in ``source``. Returns a module name or
    ``None``. This widens coverage to the full catalogue without hand-listing
    every step.
    """
    tokens = set(re.split(r"[^a-z0-9]+", source.lower()))
    tokens.discard("")
    for name, spec in modulespec.MODULE_REGISTRY.items():
        if spec.experimental:
            continue
        candidates = {name.lower()}
        if spec.picasso_symbol:
            candidates.add(spec.picasso_symbol.split(".")[-1].lower())
        if candidates & tokens:
            return name
    return None


def map_step(step, pixelsize=130.0):
    """Map one info-step dict to a :class:`MappedStep`.

    Unrecognised steps become a flagged ``manual`` placeholder carrying the
    source string, so nothing is silently dropped.
    """
    source = _source_string(step)
    low = source.lower()
    for needle, module_name, extractor in STEP_MAP:
        if needle in low:
            if module_name == SKIP_MODULE:
                # No automatic mapping (display Render, unit conversion, a
                # measurement, or a channel-alignment render with no distinct
                # info step). Keep it as a placeholder rather than dropping it,
                # so the user can remove it or pick the right module (e.g.
                # align_channels for a channel-alignment step).
                return MappedStep(
                    source=source,
                    module_name="dummy_module",
                    params={},
                    confidence=CONF_UNMAPPED,
                    messages=[
                        "no automatic mapping -- remove this row, or pick a "
                        "module (e.g. align_channels if this is a "
                        "channel-alignment step)"
                    ],
                    info_dict=step,
                )
            params = extractor(step, pixelsize)
            no_params_expected = extractor is _extract_none
            conf = CONF_OK if (params or no_params_expected) else CONF_LOW
            messages = []
            if not params and not no_params_expected:
                messages.append("parameters fell back to module defaults")
            if module_name == "filter_locs":
                conf = CONF_LOW
                messages.append(
                    "parameters not recovered from the manual step; set them "
                    "in the module"
                )
            if module_name in NOTES_BY_MODULE:
                messages.append(NOTES_BY_MODULE[module_name])
            return MappedStep(
                source=source,
                module_name=module_name,
                params=params,
                confidence=conf,
                cross_channel=module_name in CROSS_CHANNEL_MODULES,
                messages=messages,
                info_dict=step,
            )
    guess = _registry_fallback(low)
    if guess is not None:
        return MappedStep(
            source=source,
            module_name=guess,
            params={},
            confidence=CONF_LOW,
            cross_channel=guess in CROSS_CHANNEL_MODULES,
            messages=[f"best-guess mapping for '{source}'; review needed"],
        )
    return MappedStep(
        source=source,
        module_name="manual",
        params={"note": source or "unrecognised manual step"},
        confidence=CONF_UNMAPPED,
        messages=[f"could not map '{source}'; resolve before running"],
    )


def _is_movie_header(step):
    """True for the first info dict (movie/localizations header, no step)."""
    return "Generated by" not in step and "Wrapped by" not in step


def map_chain(chain, pixelsize=130.0, start_from="raw"):
    """Map every processing step of a :class:`ChannelChain` to modules.

    In ``"raw"`` mode the first info dict is the movie header and becomes the
    loader (re-localize from the raw movie), followed by every processing step.
    In ``"localizations"`` mode the channel's manual localized file is loaded
    directly and only the steps applied *after* it (``info_steps`` beyond
    ``base_info_len``) are reconstructed -- the baked-in localize/undrift steps
    are skipped. A manual identify+fit pair (both ``picasso_localize``) is
    collapsed, and any ``picasso_picked_locs`` step is pointed at the picks file.
    """
    base_name = os.path.basename(chain.base_hdf5) if chain.base_hdf5 else None
    steps = []
    if start_from == "localizations":
        loader = _localizations_loader_step()
        loader.source_file = base_name
        steps.append(loader)
        # Skip the header + the steps already baked into the localized file.
        start = max(chain.base_info_len, 1)
        for j, step in enumerate(chain.info_steps[start:], start=start):
            mapped = map_step(step, pixelsize)
            mapped.source_file = _file_for_index(chain.file_lengths, j)
            steps.append(mapped)
    else:
        saw_header = False
        for j, step in enumerate(chain.info_steps):
            if _is_movie_header(step) and not saw_header:
                saw_header = True
                steps.append(_loader_step(chain, step))
                continue
            mapped = map_step(step, pixelsize)
            mapped.source_file = _file_for_index(chain.file_lengths, j)
            steps.append(mapped)
    steps = _collapse_localize(steps)
    for s in steps:
        if s.module_name == "picasso_picked_locs" and chain.picks_path:
            s.params.setdefault("picks_file", chain.picks_path)
            s.confidence = CONF_OK
    chain.steps = steps
    return steps


def _collapse_localize(steps):
    """Merge an adjacent identify+fit pair (both ``picasso_localize``).

    A manual localization writes an Identify step then a Fit step (and the
    picasso-workflow pipeline splits identify / localize too); both map to
    ``picasso_localize``, so a run of them is folded into one module with the
    union of their recovered parameters.
    """
    collapsed = []
    for step in steps:
        if (
            collapsed
            and step.module_name == "picasso_localize"
            and collapsed[-1].module_name == "picasso_localize"
        ):
            prev = collapsed[-1]
            merged = dict(prev.params)
            merged.update(step.params)
            prev.params = merged
            prev.messages = list(dict.fromkeys(prev.messages + step.messages))
            if CONF_OK in (prev.confidence, step.confidence):
                prev.confidence = CONF_OK
            # the fit completes the localization: attribute to its file
            prev.source_file = step.source_file or prev.source_file
            continue
        collapsed.append(step)
    return collapsed


def _loader_step(chain, header):
    """Pick the loader module for a channel from the resolved raw path.

    A resolved raw movie drives ``load_dataset_movie`` (re-localize from the
    raw data). Otherwise fall back to ``load_dataset_localizations`` on the
    manual localization file -- the header's ``File`` is a staged temp path, so
    its mere presence does not mean the raw movie is available.
    """
    if chain.raw_filepath:
        return MappedStep(
            source="movie header",
            module_name="load_dataset_movie",
            params={"filename": ("$$map", "filepath")},
            confidence=CONF_OK,
            messages=[],
        )
    return MappedStep(
        source="localizations header",
        module_name="load_dataset_localizations",
        params={"filename": ("$$map", "filepath")},
        confidence=CONF_OK,
        messages=[],
    )


def _localizations_loader_step():
    """Loader for downstream mode: load the manual localized file directly."""
    return MappedStep(
        source="localized file",
        module_name="load_dataset_localizations",
        params={"filename": ("$$map", "filepath")},
        confidence=CONF_OK,
        messages=[],
    )


# ---------------------------------------------------------------------------
# 3. find_similar parameter retro-calculation.
# ---------------------------------------------------------------------------
# Note: retro_calc_find_similar and retro_calc_from_picked have similar numeric
# logic (looping over picks/groups, computing fracs and rmsds from enclosed locs,
# deriving min/max with margin). A future refactoring could extract a shared
# _retro_calc_thresholds_core(x_nm, y_nm, centers_or_groups, ...) helper.
def retro_calc_find_similar(
    locs, centers_nm, diameter_nm, pixelsize, n_frames, margin=0.1
):
    """Recover ``find_similar`` thresholds from saved picks + localizations.

    ``pick_similar`` does not persist the nlocs / rmsd thresholds it used, so
    they are reconstructed: for each saved pick centre, count the enclosed
    localizations and their RMS distance from the centre, then set the min/max
    bounds to span the observed distributions (with a relative ``margin``).

    Parameters
    ----------
    locs : numpy.recarray
        Localizations with ``x`` / ``y`` columns in camera pixels.
    centers_nm : list[tuple[float, float]]
        Saved pick centres in nm.
    diameter_nm : float
        Pick diameter in nm (from the picks yaml).
    pixelsize : float
        Camera pixel size in nm.
    n_frames : int
        Number of movie frames (to express nlocs as a per-frame fraction).
    margin : float
        Relative slack added around the observed min/max.

    Returns
    -------
    dict
        ``diameter`` (nm) plus ``min_n_locs_per_frame`` /
        ``max_n_locs_per_frame`` / ``min_rmsd`` / ``max_rmsd``. Empty when no
        pick encloses any localization.
    """
    x_nm = np.asarray(locs["x"], dtype=float) * pixelsize
    y_nm = np.asarray(locs["y"], dtype=float) * pixelsize
    radius = float(diameter_nm) / 2.0
    n_frames = max(int(n_frames or 1), 1)

    fracs = []
    rmsds = []
    for cx, cy in centers_nm:
        dx = x_nm - cx
        dy = y_nm - cy
        inside = (dx * dx + dy * dy) <= radius * radius
        n = int(np.count_nonzero(inside))
        if n == 0:
            continue
        fracs.append(n / n_frames)
        rmsds.append(
            float(np.sqrt(np.mean(dx[inside] ** 2 + dy[inside] ** 2)))
        )

    if not fracs:
        return {}

    fracs = np.asarray(fracs)
    rmsds = np.asarray(rmsds)
    return {
        "diameter": float(diameter_nm),
        "min_n_locs_per_frame": float(fracs.min() * (1 - margin)),
        "max_n_locs_per_frame": float(fracs.max() * (1 + margin)),
        "min_rmsd": float(rmsds.min() * (1 - margin)),
        "max_rmsd": float(rmsds.max() * (1 + margin)),
    }


def apply_find_similar_retrocalc(chain, pixelsize=130.0):
    """Fill retro-calculated parameters into a chain's ``find_similar`` step.

    No-op when the chain has no ``find_similar`` step or no picks file.
    Flags the step :data:`CONF_RETRO` on success.
    """
    fs_steps = [s for s in chain.steps if s.module_name == "find_similar"]
    if not fs_steps or not chain.picks_path:
        return
    centers, diameter, _shape = _load_picks_yaml(chain.picks_path)
    if not centers or not diameter:
        return
    try:
        locs, info = _load_locs(chain.base_hdf5 or chain.deepest_hdf5)
    except Exception as exc:  # pragma: no cover - depends on picasso/data
        for s in fs_steps:
            # Flag for review: the step keeps only module defaults, so it must
            # not read as a confidently-recovered module.
            s.confidence = CONF_LOW
            s.messages.append(f"could not load locs for retro-calc: {exc}")
        return
    n_frames = _n_frames_from_info(info)
    params = retro_calc_find_similar(
        locs, centers, diameter, pixelsize, n_frames
    )
    for s in fs_steps:
        if params:
            s.params.update(params)
            s.confidence = CONF_RETRO
            s.messages.append(
                "nlocs/rmsd thresholds retro-calculated from saved picks"
            )
        else:
            s.params.setdefault("diameter", float(diameter))
            s.messages.append("picks enclosed no localizations; review")


def retro_calc_from_picked(
    picked_locs, diameter_nm, pixelsize, n_frames, margin=0.1
):
    """Recover ``find_similar`` thresholds from grouped picked localizations.

    The manual *Render : Pick* saves the picked localizations with a ``group``
    column (one group per pick) but not the pick thresholds. For each group,
    count the enclosed localizations (as a per-frame fraction) and their RMS
    distance from the group centre, and set the min/max bounds to span the
    observed distributions (with a relative ``margin``). ``diameter`` comes from
    the step's ``Pick Diameter (nm)``.

    Parameters
    ----------
    picked_locs : recarray or DataFrame
        Picked localizations with ``x`` / ``y`` (camera pixels) and ``group``.
    diameter_nm : float
        Pick diameter in nm.
    pixelsize : float
        Camera pixel size in nm.
    n_frames : int
        Number of movie frames.

    Returns
    -------
    dict
        ``diameter`` plus ``min/max_n_locs_per_frame`` / ``min/max_rmsd``.
        Empty when there is no usable group column.
    """
    try:
        x = np.asarray(picked_locs["x"], dtype=float) * pixelsize
        y = np.asarray(picked_locs["y"], dtype=float) * pixelsize
        groups = np.asarray(picked_locs["group"])
    except (KeyError, ValueError, TypeError, IndexError):
        return {}
    n_frames = max(int(n_frames or 1), 1)
    fracs = []
    rmsds = []
    for g in np.unique(groups):
        mask = groups == g
        n = int(np.count_nonzero(mask))
        if n == 0:
            continue
        gx = x[mask]
        gy = y[mask]
        cx = gx.mean()
        cy = gy.mean()
        fracs.append(n / n_frames)
        rmsds.append(float(np.sqrt(np.mean((gx - cx) ** 2 + (gy - cy) ** 2))))
    if not fracs:
        return {}
    fracs = np.asarray(fracs)
    rmsds = np.asarray(rmsds)
    return {
        "diameter": float(diameter_nm),
        "min_n_locs_per_frame": float(fracs.min() * (1 - margin)),
        "max_n_locs_per_frame": float(fracs.max() * (1 + margin)),
        "min_rmsd": float(rmsds.min() * (1 - margin)),
        "max_rmsd": float(rmsds.max() * (1 + margin)),
    }


def apply_pick_similar_retrocalc(chain, manual_dir, pixelsize=130.0):
    """Note the pick-similar parameters behind a ``picasso_picked_locs`` step.

    The manual *Render : Pick* only records the pick diameter/shape, not whether
    pick-similar was used nor its thresholds. From the grouped picked
    localizations it saved, compute the ``find_similar`` thresholds and attach
    them as a note, so the user can switch the module to ``find_similar`` and
    set them to reproduce the picks. Best-effort: silent-ish on load failure.
    """
    n_frames = _n_frames_from_info(chain.info_steps)
    for s in chain.steps:
        if s.module_name != "picasso_picked_locs":
            continue
        diameter = (s.info_dict or {}).get("Pick Diameter (nm)")
        if not diameter or not s.source_file:
            continue
        path = os.path.join(manual_dir, s.source_file)
        try:
            picked, _info = _load_locs(path)
        except Exception as exc:  # pragma: no cover - depends on picasso/data
            s.messages.append(
                f"could not load picked locs to derive pick-similar "
                f"parameters: {exc}"
            )
            continue
        params = retro_calc_from_picked(picked, diameter, pixelsize, n_frames)
        if params:
            summary = ", ".join(
                f"{k}={round(v, 4)}" for k, v in params.items()
            )
            s.messages.append(
                "pick-similar parameters (if pick-similar produced these "
                f"picks): {summary} -- switch the module to find_similar and "
                "set these to reproduce the picks"
            )
        else:
            s.messages.append(
                f"pick diameter {diameter} nm; could not derive nlocs/rmsd "
                "(no group column in the picked file)"
            )


def _n_frames_from_info(info):
    """Best-effort movie frame count from an info list."""
    for step in info or []:
        if isinstance(step, dict) and "Frames" in step:
            return step["Frames"]
    return 1


