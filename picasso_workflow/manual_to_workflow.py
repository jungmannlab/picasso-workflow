#!/usr/bin/env python
"""Reconstruct a picasso-workflow from a manually-performed analysis.

A user who ran a DNA-PAINT analysis by hand in the picasso GUI leaves behind a
chain of ``.hdf5`` localization files plus their ``.yaml`` *info* sidecars. Each
processing step (localize, undrift, pick, align, cluster, ...) appends a dict to
the cumulative info list and a suffix to the filename, so the deepest file of a
channel's chain records the whole ordered history.

This module is the Qt-free engine that turns such a folder into the GUI state of
an aggregation workflow: a single-dataset module list, an aggregation module
list, a ``tree_data`` dict (datasets / channels / file paths / per-channel tile
parameters), and a per-step ``review`` list carrying a confidence flag and
messages. The thin :mod:`picasso_workflow.wizard_manual_to_workflow` Qt wizard
drives it and writes the result into the main GUI.

Design
------
* **Info yamls and pick yamls are plain YAML** and are read directly (no picasso
  import), which keeps the engine light and unit-testable with no data.
* The **only** picasso dependency is loading a base ``.hdf5`` localization table
  for the :func:`find_similar` parameter retro-calculation; it is confined to
  :func:`_load_locs` and only reached when a pick file is present.
* Mapping from a manual step to a module is **data-driven** (:data:`STEP_MAP`)
  and backed by :data:`~picasso_workflow.modulespec.MODULE_REGISTRY` for a
  best-effort fallback across the full catalogue. Nothing is ever silently
  dropped: an unrecognised step becomes a flagged ``manual`` placeholder.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, field

import numpy as np
import yaml

from picasso_workflow import modulespec

# Confidence levels surfaced in the review table.
CONF_OK = "ok"  # mapped with recovered parameters
CONF_RETRO = "retro"  # parameters retro-calculated from saved data
CONF_LOW = "low"  # mapped but parameters fell back to defaults
CONF_UNMAPPED = "unmapped"  # no confident mapping -> placeholder

# Cross-channel modules: the first one seen marks the single -> aggregation
# boundary. All of these are aggregation-scope in the registry.
CROSS_CHANNEL_MODULES = frozenset(
    {
        "align_channels",
        "register_channels",
        "combine_channels",
        "load_datasets_to_aggregate",
    }
)

# Filename suffix tokens picasso appends per processing step. Used to peel a
# channel's base stem off the deepest file and to corroborate the info order.
KNOWN_SUFFIXES = (
    "locs",
    "undrift",
    "adrift",
    "aim",
    "picked",
    "apicked",
    "pick",
    "picks",
    "align",
    "aligned",
    "render",
    "gold",
    "nogold",
    "fiducials",
    "cents",
    "centers",
    "filter",
    "filtered",
    "dbscan",
    "dbclusters",
    "hdbscan",
    "hdbclusters",
    "cluster",
    "clustered",
    "clusters",
    "molmap",
    "resi",
    "multi",
    "apicked",
    "apick",
    "properties",
    "grouped",
    "ungrouped",
    "avg",
    "ids",
    "zfit",
    "z",
)


@dataclass
class MappedStep:
    """One reconstructed module derived from a manual processing step.

    Parameters
    ----------
    source : str
        The raw ``Generated by`` / ``Wrapped by`` string of the manual step.
    module_name : str
        Target picasso-workflow module (or ``"manual"`` for a placeholder).
    params : dict
        Best-guess parameters for the module.
    confidence : str
        One of :data:`CONF_OK`, :data:`CONF_RETRO`, :data:`CONF_LOW`,
        :data:`CONF_UNMAPPED`.
    cross_channel : bool
        Whether this module needs cross-channel data (marks the boundary).
    messages : list[str]
        Human-readable notes for the review table.
    """

    source: str
    module_name: str
    params: dict = field(default_factory=dict)
    confidence: str = CONF_OK
    cross_channel: bool = False
    messages: list[str] = field(default_factory=list)


@dataclass
class ChannelChain:
    """The discovered manual-analysis artefacts for one channel."""

    tag: str  # "ALFA-L1" (channel part of the manual base name)
    dataset: str  # "Cell 1" (dataset part of the manual base name)
    base_hdf5: str | None  # shortest-stem localization file
    deepest_hdf5: str  # longest-chain file (authoritative info source)
    deepest_info_path: str  # .yaml sidecar of the deepest file
    raw_filepath: str | None  # resolved raw movie (.ome.tif)
    picks_path: str | None  # *_picks*.yaml if present
    info_steps: list[dict] = field(default_factory=list)
    suffix_ops: list[str] = field(default_factory=list)
    steps: list[MappedStep] = field(default_factory=list)


@dataclass
class ReconstructionResult:
    """Everything the wizard needs to populate the GUI.

    Attributes
    ----------
    tree_data : dict
        The aggregation Files-tree structure (``datasets`` / ``channels`` /
        ``file_paths`` / ``conditions`` / ``tile_params``).
    single_modules, agg_modules : list[tuple[str, dict]]
        Single-dataset and aggregation module lists in ``WorkflowRunner``
        ``(name, parameters)`` form.
    review : list[dict]
        One row per reconstructed module (channel-agnostic view) with keys
        ``module``, ``source``, ``confidence``, ``messages``, ``stage``.
    channels : list[str]
        Channel tags in order.
    errors : list[str]
        Consistency / validation findings (empty when clean).
    """

    tree_data: dict
    single_modules: list
    agg_modules: list
    review: list
    channels: list
    errors: list = field(default_factory=list)


# ---------------------------------------------------------------------------
# YAML / picasso I/O helpers (isolated so tests can monkeypatch them).
# ---------------------------------------------------------------------------
def _load_info(info_path):
    """Return the ordered list of info-step dicts from a ``.yaml`` sidecar.

    picasso stores the info as several ``---``-separated YAML documents; the
    first describes the movie/localizations, each later one a processing step.
    """
    with open(info_path, "r") as f:
        docs = [d for d in yaml.safe_load_all(f) if d is not None]
    return docs


def _load_picks_yaml(picks_path):
    """Return ``(centers, diameter_nm, shape)`` from a picasso picks yaml."""
    with open(picks_path, "r") as f:
        data = yaml.safe_load(f)
    centers = [tuple(c) for c in data.get("Centers", [])]
    diameter = data.get("Diameter (nm)")
    shape = data.get("Shape", "Circle")
    return centers, diameter, shape


def _load_locs(hdf5_path):
    """Load a localization table via the picasso boundary.

    Confined here because it is the one hard picasso dependency of the engine
    (needed only for the ``find_similar`` retro-calculation). Returns
    ``(locs, info)``.
    """
    from picasso_workflow import _picasso_api

    return _picasso_api.io.load_locs(hdf5_path)


# ---------------------------------------------------------------------------
# 1. Folder scan.
# ---------------------------------------------------------------------------
def _group_by_base_stem(hdf5s):
    """Group localization files into per-channel chains by prefix family.

    A channel's base file (e.g. ``"Cell 1_ALFA-L1.hdf5"``) is a prefix of every
    deeper file in its chain (``"Cell 1_ALFA-L1_cents_filter...hdf5"``). Each
    file is assigned to the *shortest* stem present that is a prefix of it
    (itself, or followed by ``_``). This is robust to unknown suffix tokens.
    When no shorter prefix exists in the set, known suffixes are peeled as a
    fallback so a lone deepest file still yields a sensible base.

    Returns
    -------
    dict[str, list[str]]
        ``{base_stem: [filenames...]}``.
    """
    stems = sorted((n[: -len(".hdf5")] for n in hdf5s), key=len)
    groups: dict[str, list[str]] = {}
    for name in hdf5s:
        stem = name[: -len(".hdf5")]
        base = None
        for cand in stems:  # shortest first
            if cand == stem or stem.startswith(cand + "_"):
                base = cand
                break
        if base is None:
            base = _strip_suffixes(stem)
        groups.setdefault(base, []).append(name)
    return groups


def _strip_suffixes(stem):
    """Peel known trailing ``_<suffix>`` tokens off a file stem.

    Returns the irreducible channel base stem, e.g.
    ``"Cell 1_ALFA-L1_cents_filter_dbscan"`` -> ``"Cell 1_ALFA-L1"``.
    """
    changed = True
    while changed:
        changed = False
        for suf in KNOWN_SUFFIXES:
            tail = "_" + suf
            if stem.lower().endswith(tail) and len(stem) > len(tail):
                stem = stem[: -len(tail)]
                changed = True
                break
    return stem


def _suffix_ops(base_stem, deepest_stem):
    """Return the ordered suffix tokens between base and deepest stem."""
    rest = deepest_stem[len(base_stem) :]
    return [t for t in rest.split("_") if t]


def _split_dataset_channel(base_stem):
    """Split a manual base stem into ``(dataset, channel)``.

    picasso manual exports are named ``"<dataset>_<channel>"`` (e.g.
    ``"Cell 1_ALFA-L1"``). The channel is the last underscore-group; the
    dataset is the remainder. Falls back to ``("dataset", stem)``.
    """
    if "_" in base_stem:
        dataset, channel = base_stem.rsplit("_", 1)
        return dataset.strip(), channel.strip()
    return "dataset", base_stem.strip()


def _resolve_raw_filepath(info_steps, root):
    """Find the raw ``.ome.tif`` for a channel from its info + the root tree.

    The first info dict records the source movie under ``File``; its basename
    (e.g. ``08_ALFA_L1_100pM_1_MMStack_Pos0.ome.tif``) identifies the raw
    acquisition folder under ``root``. Returns the resolved path or ``None``.
    """
    if not info_steps:
        return None
    file_field = info_steps[0].get("File")
    if not file_field:
        return None
    basename = os.path.basename(str(file_field))
    for dirpath, _dirs, files in os.walk(root):
        if basename in files:
            return os.path.join(dirpath, basename)
    return None


def scan_folder(root, manual_subdir="analysis_manual"):
    """Discover per-channel manual-analysis chains under ``root``.

    Parameters
    ----------
    root : str
        Dataset root folder (holds the raw acquisition subfolders and the
        manual-analysis subfolder).
    manual_subdir : str
        Name of the subfolder holding the manual ``.hdf5`` chain. The name
        varies between datasets, so the wizard lets the user override it.

    Returns
    -------
    list[ChannelChain]
        One entry per discovered channel, sorted by base stem.
    """
    manual_dir = os.path.join(root, manual_subdir)
    if not os.path.isdir(manual_dir):
        raise FileNotFoundError(
            f"manual-analysis subfolder not found: {manual_dir}"
        )

    hdf5s = [f for f in os.listdir(manual_dir) if f.lower().endswith(".hdf5")]
    groups = _group_by_base_stem(hdf5s)

    chains = []
    for base_stem in sorted(groups):
        files = groups[base_stem]
        # deepest = longest filename (longest suffix chain).
        deepest = max(files, key=len)
        base_file = base_stem + ".hdf5"
        base_path = (
            os.path.join(manual_dir, base_file) if base_file in files else None
        )
        deepest_path = os.path.join(manual_dir, deepest)
        info_path = deepest_path[: -len(".hdf5")] + ".yaml"
        info_steps = _load_info(info_path) if os.path.exists(info_path) else []
        dataset, channel = _split_dataset_channel(base_stem)
        picks_path = _find_picks_file(manual_dir, base_stem)
        chains.append(
            ChannelChain(
                tag=channel,
                dataset=dataset,
                base_hdf5=base_path,
                deepest_hdf5=deepest_path,
                deepest_info_path=info_path,
                raw_filepath=_resolve_raw_filepath(info_steps, root),
                picks_path=picks_path,
                info_steps=info_steps,
                suffix_ops=_suffix_ops(base_stem, deepest[: -len(".hdf5")]),
            )
        )
    return chains


def _find_picks_file(manual_dir, base_stem):
    """Return a ``<base>_picks*.yaml`` pick file for a channel, if any."""
    for name in os.listdir(manual_dir):
        low = name.lower()
        if (
            low.endswith(".yaml")
            and name.startswith(base_stem)
            and "pick" in low
        ):
            return os.path.join(manual_dir, name)
    return None


# ---------------------------------------------------------------------------
# 2. Step -> module mapping.
# ---------------------------------------------------------------------------
def _source_string(step):
    """Return the identifying string of an info step dict."""
    return str(step.get("Generated by") or step.get("Wrapped by") or "")


# Processing steps map to the *picasso-set* (``picasso_*``) modules, which
# recapitulate native picasso 1:1, for maximal fidelity to what was done by
# hand in the picasso GUI. Only workflow plumbing with no picasso equivalent
# (loaders, ``save_single_dataset``, the cross-channel aggregation modules) and
# the picasso-workflow-native picks helpers (``find_gold`` / ``find_similar``,
# whose selection parameters picasso never persists) stay native.
#
# Extractors translate the exact picasso info keys (see the picassosr source,
# verified against 0.12.0a3) into each ``picasso_*`` module's parameter names,
# converting nm back to camera pixels where the module expects pixels.
def _px(value_nm, pixelsize):
    """Convert an nm value to camera pixels."""
    return float(value_nm) / float(pixelsize)


def _radius_value(step):
    """Return ``(value, unit)`` for a clusterer ``Radius (<unit>)`` key.

    picasso writes the DBSCAN radius under a unit-tagged key, e.g.
    ``"Radius (nm)"`` or ``"Radius (px)"``. Returns ``None`` if absent.
    """
    for key, val in step.items():
        if isinstance(key, str) and key.startswith("Radius ("):
            unit = key[len("Radius (") :].rstrip(")").strip()
            return val, unit
    return None


def _extract_localize(step, pixelsize):
    """picasso_localize (identify+fit) with the native CLI parameter names."""
    params = {}
    if "Box Size" in step:
        params["box_side_length"] = step["Box Size"]
    if "Min. Net Gradient" in step:
        params["gradient"] = step["Min. Net Gradient"]
    if "Fit method" in step:
        params["fit_method"] = step["Fit method"]
    if "Pixelsize" in step:
        params["pixelsize"] = step["Pixelsize"]
    return params


def _extract_undrift_rcc(step, pixelsize):
    params = {}
    if "Segmentation" in step:
        params["segmentation"] = step["Segmentation"]
    return params


def _extract_undrift_aim(step, pixelsize):
    # picasso_undrift_aim takes intersectdist / roiradius in camera pixels;
    # the info records them in nm.
    params = {}
    if "Segmentation" in step:
        params["segmentation"] = step["Segmentation"]
    if "Intersect distance (nm)" in step:
        params["intersectdist"] = _px(
            step["Intersect distance (nm)"], pixelsize
        )
    if "Search regions radius (nm)" in step:
        params["roiradius"] = _px(
            step["Search regions radius (nm)"], pixelsize
        )
    return params


def _extract_link(step, pixelsize):
    # native link_locs: d_max in camera pixels (the info stores the px value
    # directly), tolerance in frames.
    params = {}
    if "Maximum Distance" in step:
        params["d_max"] = step["Maximum Distance"]
    if "Maximum Transient Dark Time" in step:
        params["tolerance"] = step["Maximum Transient Dark Time"]
    return params


def _extract_density(step, pixelsize):
    # native density: radius in camera pixels (the info records it in nm).
    params = {}
    if "Radius" in step:
        params["radius"] = _px(step["Radius"], pixelsize)
    return params


def _extract_dbscan(step, pixelsize):
    # native dbscan: radius in nm, min_samples = minimum local density.
    params = {}
    rad = _radius_value(step)
    if rad is not None:
        value, unit = rad
        params["radius"] = (
            float(value) if unit == "nm" else float(value) * pixelsize
        )
    if "Minimum local density" in step:
        params["min_samples"] = step["Minimum local density"]
    return params


def _extract_hdbscan(step, pixelsize):
    # native hdbscan: min_cluster, min_samples.
    params = {}
    if "Min. cluster" in step:
        params["min_cluster"] = step["Min. cluster"]
    if "Min. samples" in step:
        params["min_samples"] = step["Min. samples"]
    return params


def _extract_smlm(step, pixelsize):
    # native smlm_clusterer: radius in nm, min_locs.
    params = {}
    for key in ("Clustering radius xy (nm)", "Clustering radius (nm)"):
        if key in step:
            params["radius"] = step[key]
            break
    if "Min. cluster size" in step:
        params["min_locs"] = step["Min. cluster size"]
    return params


def _extract_g5m(step, pixelsize):
    params = {}
    if "Min. no. locs per molecule" in step:
        params["min_locs"] = step["Min. no. locs per molecule"]
    return params


def _extract_none(step, pixelsize):
    return {}


# Ordered matchers: (lowercased substring of the source string, module,
# extractor). First match wins. Strings are ``f"Picasso v{version} <op>"``, so
# matching is by distinctive token; order resolves substring overlaps
# ("hdbscan" before "dbscan"; "undrift from picked"/"by fiducials" before the
# generic "undrift"; the cross-channel markers before the generic "align").
STEP_MAP = [
    # --- picasso-workflow-native cross-channel markers (stay native) ---
    ("register_channels", "register_channels", _extract_none),
    ("channel registration", "register_channels", _extract_none),
    ("combine_channels", "combine_channels", _extract_none),
    ("align_channels", "align_channels", _extract_none),
    # --- picasso-workflow-native picks helpers (no picasso equivalent) ---
    ("find_gold", "find_gold", _extract_none),
    ("find_similar", "find_similar", _extract_none),
    ("find_structures", "find_structures", _extract_none),
    ("pick_origami", "pick_origami", _extract_none),
    ("undrift_from_picked", "undrift_from_picked", _extract_none),
    ("undrift from picked", "undrift_from_picked", _extract_none),
    # --- picasso-set (1:1 native picasso) processing steps ---
    ("identify", "picasso_localize", _extract_localize),
    ("fit 2d", "picasso_localize", _extract_localize),
    ("localize", "picasso_localize", _extract_localize),
    ("fit 3d", "picasso_zfit", _extract_none),
    ("zfit", "picasso_zfit", _extract_none),
    ("undrift by fiducials", "picasso_undrift_fiducials", _extract_none),
    ("aim", "picasso_undrift_aim", _extract_undrift_aim),
    ("undrift", "picasso_undrift_rcc", _extract_undrift_rcc),
    ("render : pick", "picasso_picked_locs", _extract_none),
    # --- clustering / density / link / filter: native both-scope modules,
    #     themselves 1:1 picasso wrappers, so they are valid in the
    #     aggregation stage (where post-alignment per-channel clustering runs)
    #     as well as the single stage.
    ("hdbscan", "hdbscan", _extract_hdbscan),
    ("dbscan", "dbscan", _extract_dbscan),
    ("smlm clusterer", "smlm_clusterer", _extract_smlm),
    ("g5m", "gaussian_mixture_cluster", _extract_g5m),
    ("link", "link_locs", _extract_link),
    ("density", "density", _extract_density),
    ("filter", "filter_locs", _extract_none),
    ("align", "picasso_align", _extract_none),
]


def _registry_fallback(source):
    """Best-effort map an unknown step via the module registry.

    Scans :data:`MODULE_REGISTRY` for a module whose name or picasso-symbol
    last component appears as a word in ``source``. Returns a module name or
    ``None``. This widens coverage to the full catalogue without hand-listing
    every step.
    """
    tokens = set(re.split(r"[^a-z0-9]+", source.lower()))
    tokens.discard("")
    for name, spec in modulespec.MODULE_REGISTRY.items():
        if spec.experimental:
            continue
        candidates = {name.lower()}
        if spec.picasso_symbol:
            candidates.add(spec.picasso_symbol.split(".")[-1].lower())
        if candidates & tokens:
            return name
    return None


def map_step(step, pixelsize=130.0):
    """Map one info-step dict to a :class:`MappedStep`.

    Unrecognised steps become a flagged ``manual`` placeholder carrying the
    source string, so nothing is silently dropped.
    """
    source = _source_string(step)
    low = source.lower()
    for needle, module_name, extractor in STEP_MAP:
        if needle in low:
            params = extractor(step, pixelsize)
            no_params_expected = extractor is _extract_none
            conf = CONF_OK if (params or no_params_expected) else CONF_LOW
            messages = []
            if not params and not no_params_expected:
                messages.append("parameters fell back to module defaults")
            return MappedStep(
                source=source,
                module_name=module_name,
                params=params,
                confidence=conf,
                cross_channel=module_name in CROSS_CHANNEL_MODULES,
                messages=messages,
            )
    guess = _registry_fallback(low)
    if guess is not None:
        return MappedStep(
            source=source,
            module_name=guess,
            params={},
            confidence=CONF_LOW,
            cross_channel=guess in CROSS_CHANNEL_MODULES,
            messages=[f"best-guess mapping for '{source}'; review needed"],
        )
    return MappedStep(
        source=source,
        module_name="manual",
        params={"note": source or "unrecognised manual step"},
        confidence=CONF_UNMAPPED,
        messages=[f"could not map '{source}'; resolve before running"],
    )


def _is_movie_header(step):
    """True for the first info dict (movie/localizations header, no step)."""
    return "Generated by" not in step and "Wrapped by" not in step


def map_chain(chain, pixelsize=130.0):
    """Map every processing step of a :class:`ChannelChain` to modules.

    The first info dict is the movie/localizations header; it becomes the
    loader module rather than a processing step. A manual identify+fit pair
    (both mapping to ``picasso_localize``) is collapsed into one step, and any
    ``picasso_picked_locs`` step is pointed at the channel's saved picks file.
    """
    steps = []
    saw_header = False
    for step in chain.info_steps:
        if _is_movie_header(step) and not saw_header:
            saw_header = True
            steps.append(_loader_step(chain, step))
            continue
        steps.append(map_step(step, pixelsize))
    steps = _collapse_localize(steps)
    for s in steps:
        if s.module_name == "picasso_picked_locs" and chain.picks_path:
            s.params.setdefault("picks_file", chain.picks_path)
            s.confidence = CONF_OK
    chain.steps = steps
    return steps


def _collapse_localize(steps):
    """Merge an adjacent identify+fit pair (both ``picasso_localize``).

    A manual localization writes an Identify step then a Fit step (and the
    picasso-workflow pipeline splits identify / localize too); both map to
    ``picasso_localize``, so a run of them is folded into one module with the
    union of their recovered parameters.
    """
    collapsed = []
    for step in steps:
        if (
            collapsed
            and step.module_name == "picasso_localize"
            and collapsed[-1].module_name == "picasso_localize"
        ):
            prev = collapsed[-1]
            merged = dict(prev.params)
            merged.update(step.params)
            prev.params = merged
            prev.messages = list(dict.fromkeys(prev.messages + step.messages))
            if CONF_OK in (prev.confidence, step.confidence):
                prev.confidence = CONF_OK
            continue
        collapsed.append(step)
    return collapsed


def _loader_step(chain, header):
    """Pick the loader module for a channel from its header + raw path."""
    if chain.raw_filepath or "File" in header:
        return MappedStep(
            source="movie header",
            module_name="load_dataset_movie",
            params={"filename": ("$$map", "filepath")},
            confidence=CONF_OK,
            messages=[],
        )
    return MappedStep(
        source="localizations header",
        module_name="load_dataset_localizations",
        params={"filename": ("$$map", "filepath")},
        confidence=CONF_OK,
        messages=[],
    )


# ---------------------------------------------------------------------------
# 3. find_similar parameter retro-calculation.
# ---------------------------------------------------------------------------
def retro_calc_find_similar(
    locs, centers_nm, diameter_nm, pixelsize, n_frames, margin=0.1
):
    """Recover ``find_similar`` thresholds from saved picks + localizations.

    ``pick_similar`` does not persist the nlocs / rmsd thresholds it used, so
    they are reconstructed: for each saved pick centre, count the enclosed
    localizations and their RMS distance from the centre, then set the min/max
    bounds to span the observed distributions (with a relative ``margin``).

    Parameters
    ----------
    locs : numpy.recarray
        Localizations with ``x`` / ``y`` columns in camera pixels.
    centers_nm : list[tuple[float, float]]
        Saved pick centres in nm.
    diameter_nm : float
        Pick diameter in nm (from the picks yaml).
    pixelsize : float
        Camera pixel size in nm.
    n_frames : int
        Number of movie frames (to express nlocs as a per-frame fraction).
    margin : float
        Relative slack added around the observed min/max.

    Returns
    -------
    dict
        ``diameter`` (nm) plus ``min_n_locs_per_frame`` /
        ``max_n_locs_per_frame`` / ``min_rmsd`` / ``max_rmsd``. Empty when no
        pick encloses any localization.
    """
    x_nm = np.asarray(locs["x"], dtype=float) * pixelsize
    y_nm = np.asarray(locs["y"], dtype=float) * pixelsize
    radius = float(diameter_nm) / 2.0
    n_frames = max(int(n_frames or 1), 1)

    fracs = []
    rmsds = []
    for cx, cy in centers_nm:
        dx = x_nm - cx
        dy = y_nm - cy
        inside = (dx * dx + dy * dy) <= radius * radius
        n = int(np.count_nonzero(inside))
        if n == 0:
            continue
        fracs.append(n / n_frames)
        rmsds.append(
            float(np.sqrt(np.mean(dx[inside] ** 2 + dy[inside] ** 2)))
        )

    if not fracs:
        return {}

    fracs = np.asarray(fracs)
    rmsds = np.asarray(rmsds)
    return {
        "diameter": float(diameter_nm),
        "min_n_locs_per_frame": float(fracs.min() * (1 - margin)),
        "max_n_locs_per_frame": float(fracs.max() * (1 + margin)),
        "min_rmsd": float(rmsds.min() * (1 - margin)),
        "max_rmsd": float(rmsds.max() * (1 + margin)),
    }


def apply_find_similar_retrocalc(chain, pixelsize=130.0):
    """Fill retro-calculated parameters into a chain's ``find_similar`` step.

    No-op when the chain has no ``find_similar`` step or no picks file.
    Flags the step :data:`CONF_RETRO` on success.
    """
    fs_steps = [s for s in chain.steps if s.module_name == "find_similar"]
    if not fs_steps or not chain.picks_path:
        return
    centers, diameter, _shape = _load_picks_yaml(chain.picks_path)
    if not centers or not diameter:
        return
    try:
        locs, info = _load_locs(chain.base_hdf5 or chain.deepest_hdf5)
    except Exception as exc:  # pragma: no cover - depends on picasso/data
        for s in fs_steps:
            s.messages.append(f"could not load locs for retro-calc: {exc}")
        return
    n_frames = _n_frames_from_info(info)
    params = retro_calc_find_similar(
        locs, centers, diameter, pixelsize, n_frames
    )
    for s in fs_steps:
        if params:
            s.params.update(params)
            s.confidence = CONF_RETRO
            s.messages.append(
                "nlocs/rmsd thresholds retro-calculated from saved picks"
            )
        else:
            s.params.setdefault("diameter", float(diameter))
            s.messages.append("picks enclosed no localizations; review")


def _n_frames_from_info(info):
    """Best-effort movie frame count from an info list."""
    for step in info or []:
        if isinstance(step, dict) and "Frames" in step:
            return step["Frames"]
    return 1


# ---------------------------------------------------------------------------
# 4. Single <-> aggregation split.
# ---------------------------------------------------------------------------
def split_stages(steps):
    """Split a mapped step sequence at the first cross-channel module.

    Everything before the boundary is single-dataset work (run per channel);
    the boundary module and everything after it belong to the aggregation
    stage, per the rule "move to aggregation from the first moment cross-channel
    data is needed".

    Returns
    -------
    tuple[list[MappedStep], list[MappedStep]]
        ``(single_steps, agg_steps)``.
    """
    for idx, step in enumerate(steps):
        if step.cross_channel:
            return list(steps[:idx]), list(steps[idx:])
    return list(steps), []


# ---------------------------------------------------------------------------
# 5. Per-channel parameter diffing.
# ---------------------------------------------------------------------------
def _tile_column_name(module_name, param, position):
    """Stable tile-parameter column name for a varying parameter."""
    return f"{position:02d}_{module_name}__{param}"


def diff_single_stage(per_channel_single, channels):
    """Fold per-channel single-dataset steps into one list with ``$$map``.

    Parameters position-aligned across channels are compared: identical values
    stay scalar; values that vary across channels become
    ``("$$map", "<column>", <default>)`` and the column is registered in the
    returned ``tile_params``.

    Parameters
    ----------
    per_channel_single : list[list[MappedStep]]
        One single-dataset step list per channel (assumed same spine).
    channels : list[str]
        Channel tags, aligned with ``per_channel_single``.

    Returns
    -------
    tuple[list[tuple[str, dict]], dict]
        The folded single-dataset module list and a ``tile_params`` dict
        ``{column: {channel: value}}``.
    """
    if not per_channel_single:
        return [], {}
    spine_len = min(len(s) for s in per_channel_single)
    folded = []
    tile_params: dict[str, dict] = {}
    for pos in range(spine_len):
        module_name = per_channel_single[0][pos].module_name
        # Union of parameter keys at this position across channels.
        keys = set()
        for ch_steps in per_channel_single:
            keys.update(ch_steps[pos].params.keys())
        merged = {}
        for key in sorted(keys):
            values = [ch[pos].params.get(key) for ch in per_channel_single]
            if _all_equal(values):
                merged[key] = values[0]
            else:
                col = _tile_column_name(module_name, key, pos)
                tile_params[col] = {
                    channels[i]: values[i] for i in range(len(channels))
                }
                merged[key] = ("$$map", col, values[0])
        folded.append((module_name, merged))
    return folded, tile_params


def _all_equal(values):
    """True when every value equals the first (by repr for robustness)."""
    first = repr(values[0])
    return all(repr(v) == first for v in values)


# ---------------------------------------------------------------------------
# 6. Bridge modules + aggregation list assembly.
# ---------------------------------------------------------------------------
def _save_single_bridge():
    """The ``save_single_dataset`` module closing the single stage."""
    return ("save_single_dataset", {"filename": ("$$map", "#tags")})


def _load_aggregate_bridge(save_index):
    """The ``load_datasets_to_aggregate`` module opening the aggregation stage.

    Mirrors ``standard_aggregation_workflows.cluster_aggregation``: it pulls the
    per-channel saved files via ``$$get_prior_result`` and the tags via
    ``$$map``.
    """
    prior = (
        "$$get_prior_result",
        "all_results, single_dataset, $$all, "
        f"{save_index:02d}_save_single_dataset, filepath",
    )
    return (
        "load_datasets_to_aggregate",
        {"filepaths": prior, "tags": ("$$map", "#tags")},
    )


def _steps_to_modules(steps):
    """Render mapped steps as ``(name, params)`` tuples."""
    return [(s.module_name, dict(s.params)) for s in steps]


# ---------------------------------------------------------------------------
# 7. Consistency / correctness check.
# ---------------------------------------------------------------------------
def validate(single_modules, agg_modules, chains):
    """Run registry validation + wizard-level consistency checks.

    Returns a list of human-readable findings (empty when clean).
    """
    errors = []
    errors += [
        f"single[{msg}"
        for msg in modulespec.validate_workflow(
            single_modules, modulespec.Scope.SINGLE
        )
    ]
    if agg_modules:
        errors += [
            f"aggregation[{msg}"
            for msg in modulespec.validate_workflow(
                agg_modules, modulespec.Scope.AGGREGATION
            )
        ]
    # Every channel should share the same step spine.
    spines = {tuple(s.module_name for s in c.steps) for c in chains if c.steps}
    if len(spines) > 1:
        errors.append(
            "channels have differing step sequences; review per-channel "
            "reconstruction"
        )
    # Required inputs must exist.
    for c in chains:
        if c.raw_filepath and not os.path.exists(c.raw_filepath):
            errors.append(f"raw movie not found for channel {c.tag}")
    # No unresolved placeholders.
    for c in chains:
        for s in c.steps:
            if s.confidence == CONF_UNMAPPED:
                errors.append(f"channel {c.tag}: unresolved step '{s.source}'")
    return errors


# ---------------------------------------------------------------------------
# 8. Top-level entry point.
# ---------------------------------------------------------------------------
def reconstruct_workflow(
    root, manual_subdir="analysis_manual", pixelsize=130.0
):
    """Reconstruct an aggregation workflow from a manual-analysis folder.

    Parameters
    ----------
    root : str
        Dataset root folder.
    manual_subdir : str
        Manual-analysis subfolder name (varies per dataset).
    pixelsize : float
        Camera pixel size in nm, used for the ``find_similar`` retro-calc.

    Returns
    -------
    ReconstructionResult
    """
    chains = scan_folder(root, manual_subdir)
    if not chains:
        raise ValueError(f"no manual-analysis channels found under {root}")

    for chain in chains:
        map_chain(chain, pixelsize=pixelsize)
        apply_find_similar_retrocalc(chain, pixelsize=pixelsize)

    # Split each channel, then fold the single stage with $$map.
    per_channel_single = []
    per_channel_agg = []
    for chain in chains:
        single_steps, agg_steps = split_stages(chain.steps)
        per_channel_single.append(single_steps)
        per_channel_agg.append(agg_steps)

    single_folded, tile_params = diff_single_stage(
        per_channel_single, [c.tag for c in chains]
    )
    # The aggregation spine is taken from the first channel (same across all).
    agg_steps = per_channel_agg[0] if per_channel_agg else []

    single_modules = list(single_folded)
    single_modules.append(_save_single_bridge())
    save_index = len(single_modules) - 1

    agg_modules = []
    if agg_steps:
        agg_modules.append(("analysis_documentation", {}))
        agg_modules.append(_load_aggregate_bridge(save_index))
        # The first agg step is the cross-channel boundary module itself.
        agg_modules += _steps_to_modules(agg_steps)
        agg_modules.append(("save_datasets_aggregated", {}))

    tree_data = _build_tree_data(chains, tile_params)
    review = _build_review(chains, per_channel_single, per_channel_agg)
    errors = validate(single_modules, agg_modules, chains)

    return ReconstructionResult(
        tree_data=tree_data,
        single_modules=single_modules,
        agg_modules=agg_modules,
        review=review,
        channels=[c.tag for c in chains],
        errors=errors,
    )


def _build_tree_data(chains, tile_params):
    """Assemble the GUI aggregation Files-tree structure."""
    datasets = []
    for c in chains:
        if c.dataset not in datasets:
            datasets.append(c.dataset)
    channels = [c.tag for c in chains]
    file_paths: dict[str, dict] = {}
    for c in chains:
        file_paths.setdefault(c.dataset, {})[c.tag] = (
            c.raw_filepath or c.base_hdf5 or c.deepest_hdf5
        )
    tile = {
        col: {"scope": "channel", "default": None, "values": vals}
        for col, vals in tile_params.items()
    }
    return {
        "datasets": datasets,
        "channels": channels,
        "file_paths": file_paths,
        "conditions": {},
        "tile_params": tile,
    }


def _build_review(chains, per_channel_single, per_channel_agg):
    """Build the per-module review rows from the first channel's spine."""
    review = []
    if not chains:
        return review
    first = chains[0]
    single_steps, agg_steps = split_stages(first.steps)
    for s in single_steps:
        review.append(_review_row(s, "single"))
    for s in agg_steps:
        review.append(_review_row(s, "aggregation"))
    return review


def _review_row(step, stage):
    return {
        "module": step.module_name,
        "source": step.source,
        "confidence": step.confidence,
        "messages": list(step.messages),
        "stage": stage,
        "params": dict(step.params),
    }
