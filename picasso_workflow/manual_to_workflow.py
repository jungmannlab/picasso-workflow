# YAML / picasso I/O helpers (isolated so tests can monkeypatch them).
# ---------------------------------------------------------------------------
def _load_info(info_path):
    """Return the ordered list of info-step dicts from a ``.yaml`` sidecar.

    picasso stores the info as several ``---``-separated YAML documents; the
    first describes the movie/localizations, each later one a processing step.
    """
    with open(info_path, "r") as f:
        docs = [d for d in yaml.safe_load_all(f) if d is not None]
    return docs


def _count_info_docs(yaml_path):
    """Count the YAML documents (info steps) in a sidecar, cheaply.

    Counts bare ``---`` separators without parsing the (large) movie-metadata
    document; the count is ``separators + 1``.
    """
    seps = 0
    with open(yaml_path, "r") as f:
        for line in f:
            if line.strip() == "---":
                seps += 1
    return seps + 1


def _file_for_index(file_lengths, info_index):
    """Return the manual file that first saved info step ``info_index``.

    ``file_lengths`` is a sorted ``[(doc_count, basename), ...]``; the step at
    ``info_index`` first appears in the shortest file whose info includes it
    (``doc_count > info_index``).
    """
    for doc_count, name in file_lengths:
        if doc_count > info_index:
            return name
    return None


def _load_picks_yaml(picks_path):
    """Return ``(centers, diameter_nm, shape)`` from a picasso picks yaml."""
    with open(picks_path, "r") as f:
        data = yaml.safe_load(f)
    centers = [tuple(c) for c in data.get("Centers", [])]
    diameter = data.get("Diameter (nm)")
    shape = data.get("Shape", "Circle")
    return centers, diameter, shape


def _load_locs(hdf5_path):
    """Load a localization table via the picasso boundary.

    Confined here because it is the one hard picasso dependency of the engine
    (needed only for the ``find_similar`` retro-calculation). Returns
    ``(locs, info)``.
    """
    from picasso_workflow import _picasso_api

    return _picasso_api.io.load_locs(hdf5_path)


def _report(progress, message, fraction):
    """Invoke an optional progress callback ``progress(message, fraction)``.

    ``fraction`` is a float in ``[0, 1]`` for determinate progress or ``None``
    for an indeterminate (busy) phase. A ``None`` ``progress`` is a no-op, so
    the engine stays usable headless/in tests.
    """
    if progress is not None:
        progress(message, fraction)


class ReconstructionCancelled(Exception):
    """Raised to abort an in-progress reconstruction cooperatively."""


def _source_versions(info_steps):
    """Distinct picasso versions recorded across a channel's info steps.

    From the ``"Picasso version"`` key (picasso >=1.0) or the version embedded
    in ``"Generated by: Picasso v<ver> ..."``. Returns a sorted list.
    """
    versions = set()
    for step in info_steps or []:
        if not isinstance(step, dict):
            continue
        ver = step.get("Picasso version")
        if ver:
            versions.add(str(ver))
            continue
        match = re.search(
            r"Picasso:? v([0-9][0-9A-Za-z.\-]*)",
            str(step.get("Generated by", "")),
        )
        if match:
            versions.add(match.group(1))
    return sorted(versions)


def _check_cancel(should_cancel):
    """Raise :class:`ReconstructionCancelled` if ``should_cancel()`` is true.

    ``should_cancel`` is an optional ``() -> bool`` polled at checkpoints (per
    channel) so a long scan can be stopped between channels; a single picasso
    locs load is not itself interruptible.
    """
    if should_cancel is not None and should_cancel():
        raise ReconstructionCancelled()


