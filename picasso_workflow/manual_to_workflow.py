def split_stages(steps):
    """Split a mapped step sequence at the first cross-channel module.

    Everything before the boundary is single-dataset work (run per channel);
    the boundary module and everything after it belong to the aggregation
    stage, per the rule "move to aggregation from the first moment cross-channel
    data is needed".

    Returns
    -------
    tuple[list[MappedStep], list[MappedStep]]
        ``(single_steps, agg_steps)``.
    """
    for idx, step in enumerate(steps):
        if step.cross_channel:
            return list(steps[:idx]), list(steps[idx:])
    return list(steps), []


