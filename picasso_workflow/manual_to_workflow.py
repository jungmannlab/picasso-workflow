# 1. Folder scan.
# ---------------------------------------------------------------------------
# Acquisition-format markers. A channel's movie is named ``<root>_MMStack...``
# (MicroManager) or ``<root>_NDTiffStack...`` (NDTiff); every processing output
# keeps ``<root>`` as its prefix. Detecting the marker is the most robust way to
# recover the channel, because ``<root>`` is shared by the channel's whole file
# tree -- including branches (e.g. a ``_picked`` pick export vs the main
# ``_undriftbypicked`` chain) that do not prefix one another.
_FORMAT_MARKERS = ("_mmstack", "_ndtiffstack")


def _channel_root(stem):
    """Return the acquisition root (through the format marker), or ``None``.

    ``'..._img-0-R2_NDTiffStack_locs_render_AIM_picked'`` ->
    ``'..._img-0-R2_NDTiffStack'``. ``None`` when no marker is present (the stem
    then follows the ``<dataset>_<channel>`` convention handled below).
    """
    low = stem.lower()
    for marker in _FORMAT_MARKERS:
        i = low.find(marker)
        if i > 0:
            return stem[: i + len(marker)]
    return None


def _group_by_base_stem(hdf5s):
    """Group localization files into per-channel chains.

    When an acquisition marker (``_MMStack`` / ``_NDTiffStack``) is present, the
    channel key is the acquisition root (:func:`_channel_root`): it is shared by
    every processing output of the channel, including branches (a ``_picked``
    pick export vs the main ``_undriftbypicked`` chain) that do not prefix one
    another and would otherwise scatter into separate groups when no bare base
    file is present (e.g. a minimal export of only the final + picked files).

    Otherwise each file is assigned to the *shortest* stem present that is a
    prefix of it (``"Cell 1_ALFA-L1.hdf5"`` anchors ``"Cell 1_ALFA-L1_cents
    ...hdf5"``); failing that, known suffixes are peeled so a lone deepest file
    still yields a sensible base.

    Returns
    -------
    dict[str, list[str]]
        ``{base_stem: [filenames...]}``.
    """
    stems = sorted((n[: -len(".hdf5")] for n in hdf5s), key=len)
    groups: dict[str, list[str]] = {}
    for name in hdf5s:
        stem = name[: -len(".hdf5")]
        base = _channel_root(stem)
        if base is None:
            for cand in stems:  # shortest first
                if cand == stem or stem.startswith(cand + "_"):
                    base = cand
                    break
        if base is None:
            base = _strip_suffixes(stem)
        groups.setdefault(base, []).append(name)
    return groups


def _strip_suffixes(stem):
    """Peel known trailing ``_<suffix>`` tokens off a file stem.

    Returns the irreducible channel base stem, e.g.
    ``"Cell 1_ALFA-L1_cents_filter_dbscan"`` -> ``"Cell 1_ALFA-L1"``.
    """
    changed = True
    while changed:
        changed = False
        for suf in KNOWN_SUFFIXES:
            tail = "_" + suf
            if stem.lower().endswith(tail) and len(stem) > len(tail):
                stem = stem[: -len(tail)]
                changed = True
                break
    return stem


def _split_dataset_channel(base_stem):
    """Split a manual base stem into ``(dataset, channel)``.

    Two naming conventions occur:

    * Raw-acquisition-based, e.g.
      ``"08_ALFA_L1_100pM_1_MMStack_Pos0.ome_locs_undrift_render_ali"`` -- the
      processing suffixes make the last underscore-group meaningless, so the
      channel is the acquisition root *before* the format marker (``_MMStack`` /
      ``_NDTiffStack``), e.g. ``08_ALFA_L1_100pM_1`` or
      ``prtclstep0_round_img-0-R2``, unique and human-recognizable. Rename
      channels later if wanted.
    * picasso manual exports named ``"<dataset>_<channel>"`` (e.g.
      ``"Cell 1_ALFA-L1"``) -- the channel is the last underscore-group.
    """
    low = base_stem.lower()
    for mk in _FORMAT_MARKERS:
        marker = low.find(mk)
        if marker > 0:
            return "dataset", base_stem[:marker].strip()
    if "_" in base_stem:
        dataset, channel = base_stem.rsplit("_", 1)
        return dataset.strip(), channel.strip()
    return "dataset", base_stem.strip()


def _recorded_basename(path):
    """Basename of a recorded path, tolerating Windows separators.

    The info ``File`` may be a Windows path (e.g.
    ``U:\\users\\...\\<acq>_MMStack_Pos0.ome.tif``); ``os.path.basename`` on
    Linux would not split on backslashes, so normalize them first.
    """
    return os.path.basename(str(path).replace("\\", "/"))


def _channel_basename(chain):
    """Raw-movie basename from a channel's info header, or ``None``.

    The first info dict records the source movie under ``File`` -- a staged temp
    path or a Windows acquisition path -- so only its basename is meaningful for
    locating the real file.
    """
    if chain.info_steps:
        file_field = chain.info_steps[0].get("File")
        if file_field:
            return _recorded_basename(file_field)
    return None


def _acq_folder_from_basename(basename):
    """Acquisition-folder name for a raw basename, or ``None``.

    MicroManager / NDTiff save ``<acq>/<acq>_MMStack_PosN...ome.tif`` (or
    ``<acq>_NDTiffStack...``), so the folder is the basename up to the format
    marker.
    """
    low = basename.lower()
    for mk in _FORMAT_MARKERS:
        marker = low.find(mk)
        if marker > 0:
            return basename[:marker]
    return None


def _raw_in_root(root, basename):
    """Resolve ``basename`` under ``root`` cheaply -- no deep tree walk.

    Tries the MicroManager layout ``root/<acq>/<basename>`` first (an O(1)
    stat), then ``root/<basename>`` and one level of immediate subdirectories.
    Returns the path or ``None``.
    """
    if not root or not basename:
        return None
    acq = _acq_folder_from_basename(basename)
    if acq:
        candidate = os.path.join(root, acq, basename)
        if os.path.isfile(candidate):
            return candidate
    candidate = os.path.join(root, basename)
    if os.path.isfile(candidate):
        return candidate
    try:
        for name in os.listdir(root):
            candidate = os.path.join(root, name, basename)
            if os.path.isfile(candidate):
                return candidate
    except OSError:
        pass
    return None


def _first_raw_basename(manual_dir):
    """First resolvable raw basename among a manual folder's channels."""
    try:
        hdf5s = [
            f for f in os.listdir(manual_dir) if f.lower().endswith(".hdf5")
        ]
    except OSError:
        return None
    groups = _group_by_base_stem(hdf5s)
    for base_stem in sorted(groups):
        deepest = max(groups[base_stem], key=len)
        info_path = os.path.join(
            manual_dir, deepest[: -len(".hdf5")] + ".yaml"
        )
        if os.path.exists(info_path):
            info = _load_info(info_path)
            if info and info[0].get("File"):
                return _recorded_basename(info[0]["File"])
    return None


def detect_raw_root(manual_dir, max_up=5):
    """Find the dataset root holding the raw movies for a manual folder.

    The raw acquisition folders can sit several levels above the manual-analysis
    folder (e.g. ``<root>/wfN/analysis_manual``), so walk up from ``manual_dir``
    and return the first ancestor under which a raw movie resolves (by the
    MicroManager naming convention). Returns ``None`` if none is found within
    ``max_up`` levels -- no recursive tree walk is performed.
    """
    basename = _first_raw_basename(manual_dir)
    if not basename:
        return None
    current = os.path.abspath(manual_dir)
    for _ in range(max_up + 1):
        if _raw_in_root(current, basename):
            return current
        parent = os.path.dirname(current)
        if parent == current:
            break
        current = parent
    return None


def _localize_prefix_len(info_steps):
    """Number of leading info docs that are the header or localization steps.

    Downstream mode loads already-localized data, so it reconstructs everything
    *after* localization (AIM, undrift, align, ...). The leading run is the
    movie header plus the Identify / Fit (= localize) steps; it ends at the
    first processing step. Used as ``base_info_len`` so downstream starts right
    after localization regardless of which intermediate files are present (a
    minimal export may keep only post-processing branch files, whose own depth
    would otherwise skip AIM and the undrift steps).
    """
    n = 0
    for step in info_steps:
        if _is_movie_header(step):
            n += 1
            continue
        if map_step(step).module_name == "picasso_localize":
            n += 1
            continue
        break
    return n


def _is_info_prefix(short_info, long_info):
    """True if ``short_info`` is a leading prefix of ``long_info``.

    Steps are compared by generator identity (:func:`_source_string`); the
    movie-header docs are treated as equal (a channel's files share one source
    movie). A pick side-branch (``..._picked`` export) diverges from the main
    chain at its pick step, so it is not a prefix -- which is how the scanner
    tells a clean localized checkpoint apart from a branch.
    """
    if len(short_info) > len(long_info):
        return False
    for a, b in zip(short_info, long_info):
        a_id = "" if _is_movie_header(a) else _source_string(a)
        b_id = "" if _is_movie_header(b) else _source_string(b)
        if a_id != b_id:
            return False
    return True


def scan_folder(manual_dir, progress=None, should_cancel=None):
    """Discover per-channel manual-analysis chains in ``manual_dir``.

    Reads only the manual-analysis folder (the ``.hdf5`` chain + ``.yaml``
    sidecars + pick files); raw-movie resolution, which needs the dataset root,
    is a separate step in :func:`reconstruct_workflow`.

    Parameters
    ----------
    manual_dir : str
        Folder holding the manual ``.hdf5`` step chain (e.g. ``analysis_manual``).
    progress : callable, optional
        ``progress(message, fraction)`` callback for UI feedback (see
        :func:`_report`).
    should_cancel : callable, optional
        ``() -> bool`` polled per channel to abort (see :func:`_check_cancel`).

    Returns
    -------
    list[ChannelChain]
        One entry per discovered channel, sorted by base stem.
    """
    if not os.path.isdir(manual_dir):
        raise FileNotFoundError(
            f"manual-analysis folder not found: {manual_dir}"
        )

    hdf5s = [f for f in os.listdir(manual_dir) if f.lower().endswith(".hdf5")]
    groups = _group_by_base_stem(hdf5s)

    chains = []
    ordered = sorted(groups)
    for idx, base_stem in enumerate(ordered):
        _check_cancel(should_cancel)
        _report(
            progress,
            f"Reading step history {idx + 1}/{len(ordered)}…",
            None,
        )
        files = groups[base_stem]
        # Count the info-history documents of every file in the chain up front:
        # the deepest file is the one with the MOST history, not merely the
        # longest name. picasso does not always add a filename suffix per step
        # (e.g. "Undrift from picked" is baked into whatever file is saved
        # next), so the fullest info chain can live in a file whose name is not
        # the longest.
        file_lengths = []
        for name in files:
            yaml_path = os.path.join(
                manual_dir, name[: -len(".hdf5")] + ".yaml"
            )
            if os.path.exists(yaml_path):
                file_lengths.append((_count_info_docs(yaml_path), name))
        file_lengths.sort()
        # deepest = most info steps (authoritative cumulative history);
        # shortest = earliest localized checkpoint (the downstream-mode start).
        # Fall back to filename length when no sidecars are present.
        deepest = file_lengths[-1][1] if file_lengths else max(files, key=len)
        shortest = min(files, key=len)
        deepest_path = os.path.join(manual_dir, deepest)
        info_path = deepest_path[: -len(".hdf5")] + ".yaml"
        info_steps = _load_info(info_path) if os.path.exists(info_path) else []
        # Pick the downstream-start file and how many of the deepest chain's
        # leading steps it already contains (base_info_len). Prefer a present
        # file whose history is a true prefix of the deepest chain -- a clean
        # localized checkpoint on the main branch -- and take the EARLIEST
        # (shallowest) such ancestor, so downstream reconstructs the full
        # per-channel pipeline that follows it rather than collapsing to just the
        # last step (when every intermediate file is present, the deepest
        # ancestor would skip everything). A pick side-branch is NOT a prefix, so
        # it is never chosen. When no ancestor exists (a minimal export of only
        # the final + pick-branch files), load the shortest file and reconstruct
        # everything after localization (header + Identify/Fit), so AIM and the
        # undrift steps are not skipped.
        ancestors = []
        pick_exports = {}
        for cnt, name in file_lengths:
            if name == deepest:
                continue
            cand_yaml = os.path.join(
                manual_dir, name[: -len(".hdf5")] + ".yaml"
            )
            cand_info = _load_info(cand_yaml)
            if _is_info_prefix(cand_info, info_steps):
                ancestors.append((cnt, name))
            elif (
                cand_info
                and map_step(cand_info[-1]).module_name
                == "picasso_picked_locs"
                and _is_info_prefix(cand_info[:-1], info_steps)
            ):
                # A pick-export side branch: its history is the deepest chain up
                # to <depth> plus a trailing pick, so it is the picks the
                # undrift_from_picked step at info index <depth> undrifted by.
                pick_exports[len(cand_info) - 1] = os.path.join(
                    manual_dir, name
                )
        if ancestors:
            base_info_len, base_name = min(ancestors)
            base_path = os.path.join(manual_dir, base_name)
        else:
            base_path = os.path.join(manual_dir, shortest)
            base_info_len = _localize_prefix_len(info_steps)
        dataset, channel = _split_dataset_channel(base_stem)
        picks_path = _find_picks_file(manual_dir, base_stem)
        chains.append(
            ChannelChain(
                tag=channel,
                dataset=dataset,
                base_hdf5=base_path,
                deepest_hdf5=deepest_path,
                raw_filepath=None,
                picks_path=picks_path,
                pick_exports=pick_exports,
                info_steps=info_steps,
                base_info_len=base_info_len,
                file_lengths=file_lengths,
            )
        )
    return chains


def _find_picks_file(manual_dir, base_stem):
    """Return a ``<base>_picks*.yaml`` pick file for a channel, if any.

    A picks file is a standalone pick-regions YAML. It is distinguished from
    picasso's per-step *info* sidecars (e.g. ``..._picked.yaml`` /
    ``..._apicked.yaml``, which also contain the substring ``"pick"``) by the
    absence of a matching ``.hdf5`` sibling: every info sidecar pairs with a
    same-stem localization file, a picks-regions file does not.
    """
    for name in os.listdir(manual_dir):
        low = name.lower()
        if not (low.endswith(".yaml") and name.startswith(base_stem)):
            continue
        if "pick" not in low:
            continue
        # Skip per-step info sidecars (they pair with a same-stem .hdf5).
        hdf5_sibling = os.path.join(
            manual_dir, name[: -len(".yaml")] + ".hdf5"
        )
        if os.path.exists(hdf5_sibling):
            continue
        return os.path.join(manual_dir, name)
    return None


