class _StubWindow:
    """Duck-typed stand-in for the GUI Window used by the population helper."""

    def __init__(self):
        self.single_workflow_modules = []
        self.aggregation_workflow_modules = []
        self.single_workflow_list = object()
        self.aggregation_workflow_list = object()
        self.tabs = self
        self.restored = None
        self.refreshed = []
        self.palette_refreshed = False
        self.current_tab = None

    def _restore_dataset_table(self, gui_table):
        self.restored = gui_table

    def _refresh_workflow_list(self, list_widget, modules):
        self.refreshed.append((list_widget, list(modules)))

    def _refresh_module_palette(self):
        self.palette_refreshed = True

    def setCurrentIndex(self, idx):
        self.current_tab = idx


def test_apply_result_to_window(tmp_path):
    from picasso_workflow import wizard_manual_to_workflow as wiz

    root = _make_dataset(tmp_path, CHANNELS)
    result = m.reconstruct_workflow(root)
    win = _StubWindow()
    wiz.apply_result_to_window(win, result)

    assert win.restored["workflow_type"] == 1
    assert win.restored["tree_data"] is result.tree_data
    assert win.single_workflow_modules == list(result.single_modules)
    assert win.aggregation_workflow_modules == list(result.agg_modules)
    assert win.palette_refreshed
    assert win.current_tab == 0
    assert len(win.refreshed) == 2


def test_reconstruct_flags_unmapped_step(tmp_path):
    channels = [
        (
            "Cell 1_ALFA-L1",
            "08_ALFA_L1_100pM_1",
            "08_ALFA_L1_100pM_1_MMStack_Pos0.ome.tif",
            11,
        )
    ]
    root = tmp_path / "root"
    man = root / "analysis_manual"
    man.mkdir(parents=True)
    raw = root / channels[0][1]
    raw.mkdir()
    (raw / channels[0][2]).write_text("")
    docs = _chain_docs(
        channels[0][2],
        11,
        extra=[{"Generated by": "mystery unmappable operation"}],
    )
    base = channels[0][0]
    (man / f"{base}.hdf5").write_text("")
    (man / f"{base}_cents_mystery.hdf5").write_text("")
    with open(man / f"{base}_cents_mystery.yaml", "w") as f:
        yaml.safe_dump_all(docs, f)

    res = m.reconstruct_workflow(str(root))
    # The unmapped step surfaces as a placeholder and a validation error.
    confidences = [r["confidence"] for r in res.review]
    assert m.CONF_UNMAPPED in confidences
    assert any("unresolved" in e for e in res.errors)
