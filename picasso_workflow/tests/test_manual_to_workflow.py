def _chain_docs(tif, box_size, extra=None):
    """A cumulative info list: header + the common DNA-PAINT step chain."""
    docs = [
        {"File": f"/tmp/stage/{tif}", "Frames": 40000, "Width": 576},
        {
            "Generated by": "picasso-workflow : identify",
            "Box Size": box_size,
            "Min. Net Gradient": 10000.0,
        },
        {
            "Generated by": "Picasso Localize",
            "Box Size": box_size,
            "Fit method": "spline-mle",
        },
        {
            "Generated by": "Picasso v0.11.1 AIM",
            "Segmentation": 100,
            "Intersect distance (nm)": 20.0,
            "Search regions radius (nm)": 100.0,
        },
        {"Generated by": "picasso-workflow.analyse.find_gold", "data": "gold"},
        {"Generated by": "picasso-workflow : align_channels", "shifts": "..."},
        {"Generated by": "Picasso Density", "Radius": 20.0},
    ]
    if extra:
        docs.extend(extra)
    return docs


def _make_dataset(tmp_path, channels, manual="analysis_manual"):
    """Write a synthetic dataset root with raw folders + a manual chain.

    ``channels`` is a list of ``(base_stem, raw_folder, tif, box_size)``.
    """
    root = tmp_path / "dataset_root"
    man = root / manual
    man.mkdir(parents=True)
    for base, raw_folder, tif, box in channels:
        raw_dir = root / raw_folder
        raw_dir.mkdir()
        (raw_dir / tif).write_text("")
        deep = f"{base}_cents_filter_dbscan_density"
        (man / f"{base}.hdf5").write_text("")
        (man / f"{deep}.hdf5").write_text("")
        with open(man / f"{deep}.yaml", "w") as f:
            yaml.safe_dump_all(_chain_docs(tif, box), f)
    return str(root)


