def test_retro_calc_find_similar_spans_distribution():
    # Two picks: ~1 and ~3 locs; distinct rmsd. Pixelsize 130 nm.
    px = 130.0
    locs = np.rec.fromarrays(
        [
            np.array([10.0, 50.0, 50.1, 49.9]),
            np.array([10.0, 50.0, 50.1, 49.9]),
        ],
        names="x,y",
    )
    centers = [(10 * px, 10 * px), (50 * px, 50 * px)]
    params = m.retro_calc_find_similar(
        locs, centers, diameter_nm=800.0, pixelsize=px, n_frames=100
    )
    assert params["diameter"] == 800.0
    # 1 loc and 3 locs over 100 frames -> fractions 0.01 and 0.03.
    assert params["min_n_locs_per_frame"] <= 0.01
    assert params["max_n_locs_per_frame"] >= 0.03
    assert params["min_rmsd"] <= params["max_rmsd"]


def test_retro_calc_empty_when_no_locs_in_picks():
    locs = np.rec.fromarrays([np.array([0.0]), np.array([0.0])], names="x,y")
    centers = [(10_000.0, 10_000.0)]
    assert m.retro_calc_find_similar(locs, centers, 100.0, 130.0, 10) == {}


def test_apply_find_similar_retrocalc_monkeypatched(tmp_path, monkeypatch):
    man = tmp_path / "root" / "analysis_manual"
    man.mkdir(parents=True)
    base = man / "Cell 1_ALFA-L1.hdf5"
    base.write_text("")
    picks = man / "Cell 1_ALFA-L1_picks_cents.yaml"
    with open(picks, "w") as f:
        yaml.safe_dump(
            {
                "Centers": [[1300.0, 1300.0]],
                "Diameter (nm)": 800.0,
                "Shape": "Circle",
            },
            f,
        )
    chain = m.ChannelChain(
        tag="ALFA-L1",
        dataset="Cell 1",
        base_hdf5=str(base),
        deepest_hdf5=str(base),
        deepest_info_path="",
        raw_filepath=None,
        picks_path=str(picks),
        steps=[
            m.MappedStep(source="pick_similar", module_name="find_similar")
        ],
    )
    locs = np.rec.fromarrays(
        [np.array([10.0, 10.0]), np.array([10.0, 10.0])], names="x,y"
    )
    monkeypatch.setattr(m, "_load_locs", lambda p: (locs, [{"Frames": 100}]))
    m.apply_find_similar_retrocalc(chain, pixelsize=130.0)
    fs = chain.steps[0]
    assert fs.confidence == m.CONF_RETRO
    assert "diameter" in fs.params
    assert "min_rmsd" in fs.params


