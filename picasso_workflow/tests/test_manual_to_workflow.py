def test_downstream_mode_from_localizations(tmp_path):
    # Base localized file (identify + AIM) + a deeper file adding DBSCAN.
    man = tmp_path / "root" / "analysis_manual"
    man.mkdir(parents=True)
    base_docs = [
        {
            "File": "/tmp/08_ALFA_L1_100pM_1_MMStack_Pos0.ome.tif",
            "Frames": 40000,
        },
        {
            "Generated by": "Picasso: v1.0.0rc1 Identify",
            "Box Size": 11,
            "Min. Net Gradient": 10000.0,
        },
        {
            "Generated by": "Picasso v1.0.0rc1 AIM",
            "Segmentation": 100,
            "Intersect distance (nm)": 20.0,
            "Search regions radius (nm)": 100.0,
        },
    ]
    deep_docs = base_docs + [
        {
            "Generated by": "Picasso v1.0.0rc1 DBSCAN",
            "Radius (nm)": 5.0,
            "Minimum local density": 10,
        },
    ]
    base = "Cell 1_ALFA-L1"
    (man / f"{base}.hdf5").write_text("")
    (man / f"{base}_dbscan.hdf5").write_text("")
    with open(man / f"{base}.yaml", "w") as f:
        yaml.safe_dump_all(base_docs, f)
    with open(man / f"{base}_dbscan.yaml", "w") as f:
        yaml.safe_dump_all(deep_docs, f)

    res = m.reconstruct_workflow(str(man), start_from="localizations")
    names = [n for n, _ in res.single_modules]
    # Load the localized file directly; the baked-in localize/undrift steps
    # are skipped; only the downstream DBSCAN remains.
    assert names == [
        "load_dataset_localizations",
        "picasso_dbscan",
        "save_single_dataset",
    ]
    assert res.raw_root is None
    fp = res.tree_data["file_paths"]["Cell 1"]["ALFA-L1"]
    assert fp.endswith(f"{base}.hdf5")
    assert [e for e in res.errors if not e.startswith("info:")] == []


