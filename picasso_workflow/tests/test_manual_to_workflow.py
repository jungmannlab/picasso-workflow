def test_reconstruct_workflow_golden(tmp_path):
    root = _make_dataset(tmp_path, CHANNELS)
    res = m.reconstruct_workflow(_manual(root))

    assert res.channels == ["ALFA-L1", "ALFA-R2"]

    single_names = [n for n, _ in res.single_modules]
    # The identify + Localize pair collapses onto one picasso_localize.
    assert single_names == [
        "load_dataset_movie",
        "picasso_localize",
        "picasso_undrift_aim",
        "find_gold",
        "save_single_dataset",
    ]
    agg_names = [n for n, _ in res.agg_modules]
    # Post-alignment clustering uses the native both-scope density module
    # (valid in the aggregation stage).
    assert agg_names == [
        "analysis_documentation",
        "load_datasets_to_aggregate",
        "align_channels",
        "density",
        "save_datasets_aggregated",
    ]

    # box size differs across channels -> lifted to $$map tile params on the
    # picasso_localize box_side_length parameter.
