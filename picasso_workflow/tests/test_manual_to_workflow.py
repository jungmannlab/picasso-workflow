    root = _make_dataset(tmp_path, CHANNELS)
    chains = m.scan_folder(root)
    assert [c.tag for c in chains] == ["ALFA-L1", "ALFA-R2"]
    assert all(c.dataset == "Cell 1" for c in chains)
