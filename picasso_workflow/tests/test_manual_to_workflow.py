# Per-channel diffing.
# ---------------------------------------------------------------------------
def test_diff_single_stage_scalar_vs_map():
    ch0 = [
        m.MappedStep(
            source="",
            module_name="identify",
            params={"box_size": 11, "min_gradient": 5000.0},
        )
    ]
    ch1 = [
        m.MappedStep(
            source="",
            module_name="identify",
            params={"box_size": 13, "min_gradient": 5000.0},
        )
    ]
    folded, tile = m.diff_single_stage([ch0, ch1], ["c0", "c1"])
    name, params = folded[0]
    assert name == "identify"
    # min_gradient identical -> scalar; box_size varies -> $$map.
    assert params["min_gradient"] == 5000.0
    assert params["box_size"][0] == "$$map"
    col = params["box_size"][1]
    assert tile[col] == {"c0": 11, "c1": 13}


# ---------------------------------------------------------------------------
# End-to-end reconstruct (golden structure).
# ---------------------------------------------------------------------------
def test_reconstruct_workflow_golden(tmp_path):
    root = _make_dataset(tmp_path, CHANNELS)
    res = m.reconstruct_workflow(root)

    assert res.channels == ["ALFA-L1", "ALFA-R2"]

    single_names = [n for n, _ in res.single_modules]
    assert single_names == [
        "load_dataset_movie",
        "identify",
        "localize",
        "undrift_aim",
        "find_gold",
        "save_single_dataset",
    ]
    agg_names = [n for n, _ in res.agg_modules]
    assert agg_names == [
        "analysis_documentation",
        "load_datasets_to_aggregate",
        "align_channels",
        "density",
        "save_datasets_aggregated",
    ]

    # box_size differs across channels -> lifted to $$map tile params.
    tile_cols = list(res.tree_data["tile_params"])
    assert any("identify__box_size" in c for c in tile_cols)

    # The aggregation bridge references the right save index.
    load_agg = dict(res.agg_modules)["load_datasets_to_aggregate"]
    save_idx = single_names.index("save_single_dataset")
    assert f"{save_idx:02d}_save_single_dataset" in load_agg["filepaths"][1]

    # Reconstruction validates cleanly against the module registry.
    assert res.errors == []


