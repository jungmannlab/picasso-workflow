def _run_id_for(fp: str) -> str:
    """The content-aware run_id the ingest mints for a dataset (keys label CSVs
    in tests the same way :func:`ingest.ingest_dataset` does)."""
    locs, info = io.load_locs(fp)
    return synth_run_id(fp, info, locs_signature(locs))


# Deterministic synthetic constants so "computed metrics match expected" is
# a real equality, not a smoke test.
PIXELSIZE_NM = 130.0
WIDTH = HEIGHT = 128
FRAMES = 500
N_LOCS = 3000
PHOTONS = 2500.0
BG = 75.0
SX = SY = 1.2
LPX = LPY = 0.1  # px → 13 nm


def _make_locs(
    dirpath: str,
    name: str,
    *,
    seed: int = 0,
    pixelsize: float | None = PIXELSIZE_NM,
    n: int = N_LOCS,
) -> str:
    """Write a deterministic synthetic ``_locs.hdf5`` + ``.yaml``.

    Constant photons/bg/sx/sy/lpx/lpy so the medians are exact; positions are
    random (seeded) so NeNA has a real nearest-neighbour distribution to fit.
    ``pixelsize=None`` omits ``Pixelsize`` from the info → a metadata-INcomplete
    dataset (the saver still needs Width/Height/Frames).
    """
    rng = np.random.default_rng(seed)
    locs = pd.DataFrame(
        {
            "frame": rng.integers(0, FRAMES, n).astype(np.uint32),
            "x": rng.uniform(0, WIDTH, n).astype(np.float32),
            "y": rng.uniform(0, HEIGHT, n).astype(np.float32),
            "photons": np.full(n, PHOTONS, dtype=np.float32),
            "sx": np.full(n, SX, dtype=np.float32),
            "sy": np.full(n, SY, dtype=np.float32),
            "bg": np.full(n, BG, dtype=np.float32),
            "lpx": np.full(n, LPX, dtype=np.float32),
            "lpy": np.full(n, LPY, dtype=np.float32),
            "net_gradient": np.full(n, 1500.0, dtype=np.float32),
        }
    )
    info = {
        "Width": WIDTH,
        "Height": HEIGHT,
        "Frames": FRAMES,
        "Generated by": "test",
    }
    if pixelsize is not None:
        info["Pixelsize"] = pixelsize
    fp = os.path.join(dirpath, name)
    io.save_locs(fp, locs, [info])
    return fp


